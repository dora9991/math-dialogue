    Q('（第3四分位数）−（第1四分位数）で求められる値を、何というか。', 1, '四分位範囲', 20),
    CH('上の（2）のデータに、50 が加わると、中央値と四分位範囲は、それぞれ、いくつになるか。', 2, `中央値 ${a9[2]}　　四分位範囲 ${a9[3]}−${a9[1]}＝${a9[3] - a9[1]}`, ck(A8.concat(50)))
