def tw(a, b):
    m = lcm(a.denominator, b.denominator)
    return m, a.numerator * (m // a.denominator), b.numerator * (m // b.denominator)
def pair(a, b):
    m, x, y = tw(a, b); return f'{x}/{m} と {y}/{m}'
