from lib import *
L = Lesson('baiyaku-03')
div = lambda n: [k for k in range(1, n+1) if n % k == 0]
j = lambda xs: '、'.join(map(str, xs))
assert 12 % 4 == 0
L.add(1, 'あめが 12こ あります。同じ 数ずつ ふくろに 入れて、ちょうど ぴったり に なる のは どれですか。', '4こずつ',
 [('5こずつ','2ふくろ で 10こ、2こ あまる'),('7こずつ','1ふくろ で 5こ あまる'),('8こずつ','1ふくろ で 4こ あまる')],
 '12 ÷ 4 = 3 で ぴったり。12 を わりきれる 数が 12 の 約数。\nこたえ 4こずつ', 'ブロックを 同じ 数ずつ 分けて みよう。')
assert [n for n in (2,4,5,7) if 6 % n == 0] == [2]
L.add(1, '次の 数の うち、6 の 約数は どれですか。', '2', [('4','6 ÷ 4 = 1 あまり 2'),('5','6 ÷ 5 = 1 あまり 1'),('7','6 は 7 で わりきれない')],
 '6 ÷ 2 = 3 で わりきれる。6 の 約数は 1、2、3、6。\nこたえ 2', '6 を その 数で わって あまりが 0 か 見よう。')
d = div(9)
L.add(1, '9 の 約数を ぜんぶ 書いた のは どれですか。', j(d),
 [('3、9','1 が ぬけている'),('1、3','9 が ぬけている'),('1、3、6、9','6 は 9 の 約数 では ない')],
 '9 ÷ 1 = 9、9 ÷ 3 = 3、9 ÷ 9 = 1 で わりきれる。\nこたえ 1、3、9', '1 から じゅんに わりきれるか 見よう。')
L.add(1, 'どんな 整数でも わりきれる 数は どれですか。', '1', [('0','0 で わる ことは できない'),('2','奇数は わりきれない'),('10','10 で わりきれない 数が ある')],
 'どんな 整数も 1 で わると わりきれる。1 は すべての 整数の 約数。\nこたえ 1', '5、7、13 を 1 で わって みよう。')
a = len(div(8)); assert a == 4
L.add(1, '8 の 約数は ぜんぶで 何こ ありますか。', f'{a}こ', [('3こ','1、2、4 だけ 数えた'),('5こ','3 は 8 の 約数 では ない'),('8こ','1 から 8 ぜんぶ を 数えた')],
 '8 の 約数は 1、2、4、8 の 4こ。\nこたえ 4こ', '1 から 8 まで わりきれる 数を さがそう。')
# L2
d = div(18)
L.add(2, '18 の 約数を ぜんぶ 書いた のは どれですか。', j(d),
 [('1、2、3、9、18','6 が ぬけている'),('2、3、6、9','1 と 18 が ぬけている'),('1、2、3、6、9、12、18','12 は 18 の 約数 では ない')],
 '18 = 1 × 18 = 2 × 9 = 3 × 6。\nこたえ 1、2、3、6、9、18', 'かけ算の 組で もれなく さがそう。')
assert [n for n in (4,5,8,10) if 20 % n] == [8]
L.add(2, '20 の 約数 で ない 数は どれですか。', '8', [('4','20 ÷ 4 = 5'),('5','20 ÷ 5 = 4'),('10','20 ÷ 10 = 2')],
 '20 ÷ 8 = 2 あまり 4 で わりきれない。\nこたえ 8', '20 を わって あまりが 出る 数を さがそう。')
d = div(16); a = d[-2]; assert a == 8
L.add(2, '16 の 約数の うち、2番目に 大きい 数は いくつですか。', str(a), [('16','いちばん 大きい 数'),('4','3番目に 大きい'),('2','小さい ほうの 数')],
 '16 の 約数は 1、2、4、8、16。大きい ほうから 16、8。\nこたえ 8', '約数を ぜんぶ 書いてから 大きい じゅんに ならべよう。')
d = div(30); a = len(d); assert a == 8
L.add(2, '30 の 約数は ぜんぶで 何こ ありますか。', f'{a}こ', [('6こ','10 と 15 を 数え わすれた'),('7こ','1つ 数え わすれた'),('10こ','1つ 多く 数えた')],
 '30 の 約数は 1、2、3、5、6、10、15、30 の 8こ。\nこたえ 8こ', '30 = 1 × 30 = 2 × 15 = 3 × 10 = 5 × 6 から さがそう。')
cd = [n for n in div(8) if 12 % n == 0]; assert cd == [1,2,4]
L.add(2, '8 と 12 の 公約数を ぜんぶ 書いた のは どれですか。', j(cd),
 [('2、4','1 が ぬけている'),('1、2、4、8','8 は 12 の 約数 では ない'),('1、2、3、4','3 は 8 の 約数 では ない')],
 '8 の 約数 1、2、4、8 と 12 の 約数 1、2、3、4、6、12 で 同じ 数。\nこたえ 1、2、4', '2つの 約数を 書き ならべよう。')
# L3
a = len(div(36)); assert a == 9
L.add(3, '36 の 約数を、かけ算の 組 1 × 36、2 × 18、3 × 12、4 × 9、6 × 6 から さがします。約数は ぜんぶで 何こ ですか。', f'{a}こ',
 [('10こ','6 × 6 の 6 を 2こ と 数えた'),('5こ','組の 数 を 答えた'),('8こ','1つ 数え わすれた')],
 '1、2、3、4、6、9、12、18、36 の 9こ。6 は 1こ だけ。\nこたえ 9こ', '同じ 数が 2回 でる ときは 1こ と 数えよう。')
g = gcd(12, 18)
L.add(3, '12 と 18 の 最大公約数は いくつですか。', str(g), [('3','もっと 大きい 公約数 が ある'),('36','最小公倍数 を 答えた'),('2','もっと 大きい 公約数 が ある')],
 '12 の 約数 1、2、3、4、6、12。18 の 約数 1、2、3、6、9、18。公約数 の 中で 最大 は 6。\nこたえ 6', '12 と 18 の 約数を 書いて 同じ 数を 見よう。')
cands = (5, 8, 9, 6); assert [n for n in cands if 24 % n == 0 and 36 % n == 0] == [6]
L.add(3, 'あめ 24こ と クッキー 36まいを、何人かの 子どもに あまり なく 同じ 数ずつ くばります。人数 として できる のは どれですか。', '6人',
 [('5人','24 も 36 も 5 で わりきれない'),('8人','36 は 8 で わりきれない'),('9人','24 は 9 で わりきれない')],
 '24 と 36 の 公約数 に なる 人数。6 なら 24 ÷ 6 = 4、36 ÷ 6 = 6。\nこたえ 6人', '24 も 36 も わりきれる 数を さがそう。')
c = [n for n in div(7) if 9 % n == 0]; assert c == [1]
L.add(3, '7 と 9 の 公約数は ぜんぶで 何こ ありますか。', f'{len(c)}こ', [('0こ','どんな 整数にも 1 は 約数'),('2こ','1 の ほかに ない'),('3こ','1 の ほかに ない')],
 '7 の 約数は 1、7。9 の 約数は 1、3、9。同じ 数は 1 だけ。\nこたえ 1こ', 'それぞれ の 約数を 書き ならべよう。')
L.add(3, '約数と 倍数に ついて、正しい のは どれですか。', '約数の 数には かぎりが ある',
 [('約数は ずっと つづいて おわらない','約数は その 数 より 大きく ならない'),('約数に その 数より 大きい 数が ある','12 の 約数は 12 まで'),('どんな 数も 約数は 2つ だけ','12 は 6こ ある')],
 '12 の 約数は 1 から 12 までの 6こ。約数は その 数 より 大きく ならないので かぎりが ある。\nこたえ 約数の 数には かぎりが ある', '12 の 約数と 12 の 倍数を くらべよう。')
