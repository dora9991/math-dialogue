from lib import *
L = Lesson('wariai-05'); Q = L.Q
# ---- 段階1
Q(1, "1000円の 品物が 20% 引きで 売られて います。代金は 何円ですか。", "800円",
  [("200円", "ひく 分の 金がくを 答えた"), ("1200円", "20% を たして しまった"), ("20000円", "20% を 0.2 に 直さず、20を かけた")],
  "ひく 分：1000 × 0.2 = 200円\n代金：1000 − 200 = 800円（1000 × 0.8 でも 同じ）\nこたえ 800円", "20% 引きの 代金は、もとの ねだんの 80% だよ。", val=D(1000)*D('0.8'))
Q(1, "180g入りの おかしが、25% 増量中です。ふえる 分は 何gですか。", "45g",
  [("4500g", "25% を 0.25 に 直さず、25を かけた"), ("7.2g", "180 ÷ 25 を 計算した"), ("135g", "25% を ひいた 分を 答えた")],
  "ふえる 分：180 × 0.25 = 45g\nこたえ 45g", "もとの 180g が もとにする量だよ。", val=D(180)*D('0.25'))
Q(1, "ある 量が 30% ふえました。ふえた あとの 量は、もとの 何% ですか。", "130%",
  [("30%", "ふえた 分だけを 答えた"), ("70%", "30% へった ときと まちがえた"), ("103%", "100と 3を たした")],
  "もとの 量は 100%。そこに 30% ふえる ので、100 + 30 = 130。\nこたえ 130%", "もとの 量を 100% と 見よう。")
Q(1, "ある 量が 20% へりました。へった あとの 量は、もとの 何% ですか。", "80%",
  [("20%", "へった 分だけを 答えた"), ("120%", "20% ふえた ときと まちがえた"), ("98%", "100から 2を ひいた")],
  "もとの 量は 100%。そこから 20% へる ので、100 − 20 = 80。\nこたえ 80%", "もとの 量を 100% と 見よう。")
Q(1, "下の 帯グラフは、すきな くだものの わりあいです。ぶどうは 何% ですか。", "20%",
  [("60%", "右はしの めもりを そのまま 読んだ"), ("40%", "左はしの めもりを そのまま 読んだ"), ("10%", "となりの 「その他」を 読んだ")],
  "ぶどうは めもりの 40 から 60 まで。\n60 − 40 = 20\nこたえ 20%", "右はしの めもり − 左はしの めもり で 読もう。", f=figs.band(['もも', 'ぶどう', 'みかん', 'その他'], [40, 20, 30, 10]), val=60-40)
