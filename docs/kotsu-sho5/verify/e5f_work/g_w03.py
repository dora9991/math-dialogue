Q(4, "「400mLの 30%」と「300mLの 45%」では、どちらが 多いですか。", "300mLの 45%",
  [("400mLの 30%", "もとにする量が 大きい ほうを えらんだ"), ("どちらも 同じ", "計算しないで 同じだと 思った"), ("くらべられない", "ぜんたいの 数が ちがうと くらべられないと 思った")],
  "400 × 0.3 = 120mL\n300 × 0.45 = 135mL\n135 の ほうが 大きい。\nこたえ 300mLの 45%", "べつべつに 何mLか 計算して くらべよう。", val='300mLの 45%')
Q(4, "5年生 50人の 40% が 女子です。その 女子の 25% が めがねを かけて います。めがねの 女子は 何人ですか。", "5人",
  [("20人", "女子の 人数で とまった"), ("12.5人", "50人の 25% を 求めた"), ("15人", "40 − 25 = 15 と 考えた")],
  "女子：50 × 0.4 = 20人\nめがね：20 × 0.25 = 5人\n（2つ目の もとにする量は 女子の 20人）\nこたえ 5人", "2つ目の わりあいの もとにする量は 何人かな。", val=D(50)*D('0.4')*D('0.25'))
Q(4, "先週、公園に 来た 人は 400人でした。今週は 先週の 115% でした。今週 来た 人は 何人ですか。", "460人",
  [("60人", "ふえた 分だけ 答えた"), ("46人", "115% を 0.115 に 直した"), ("4600人", "115% を 11.5 に 直した")],
  "115% ＝ 1.15\n400 × 1.15 = 460\nこたえ 460人", "115% は 小数で いくつかな。先週の 人数が もとにする量だよ。", val=D(400)*D('1.15'))
Q(4, "40人の 50% と 同じ 人数に なる のは どれですか。", "80人の 25%",
  [("50人の 50%", "もとにする量が 大きいと 人数も 大きいと 思った"), ("30人の 80%", None), ("60人の 25%", "25% が 同じだと 思った")],
  "40 × 0.5 = 20人\n80 × 0.25 = 20、50 × 0.5 = 25、30 × 0.8 = 24、60 × 0.25 = 15\nこたえ 80人の 25%", "まず 40人の 50% を 計算しよう。", val='80人の 25%')
assert 40*0.5 == 80*0.25 == 20 and all(a*b != 20 for a,b in [(50,0.5),(30,0.8),(60,0.25)])
assert D(400)*D('0.3') < D(300)*D('0.45')
