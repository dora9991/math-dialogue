from lib import *
L = Lesson('wariai-03'); Q = L.Q
# ---- 段階1
Q(1, "お茶が 400mL あります。その 30% は 何mLですか。", "120mL",
  [("12000mL", "30% を 0.3 に 直さず、30を かけた"), ("12mL", "30% を 0.03 に 直した"), ("370mL", "400から 30を ひいた")],
  "30% ＝ 0.3 なので、もとにする量に 0.3 を かける。\n400 × 0.3 = 120\nこたえ 120mL", "％を 小数に 直して、もとにする量に かけよう。", val=D(400)*D('0.3'))
Q(1, "比べる量を 求める しきは どれですか。", "もとにする量 × わりあい",
  [("もとにする量 ÷ わりあい", "わり算で 求めると 思った"), ("もとにする量 ＋ わりあい", "たし算で 求めると 思った"), ("もとにする量 − わりあい", "ひき算で 求めると 思った")],
  "わりあい ＝ 比べる量 ÷ もとにする量 だから、\n比べる量 ＝ もとにする量 × わりあい。\nこたえ もとにする量 × わりあい", "わりあいの しきを 思い出して、かけ算に かえよう。")
Q(1, "お茶が 600mL あります。下の 図の テープは、お茶ぜんたいを 10こに 同じ 大きさで 分けた ものです。ぬった ところは ぜんたいの 60% です。ぬった ところは 何mL ですか。", "360mL",
  [("60mL", "1こ分を 答えた"), ("240mL", "ぬって いない ところを 答えた"), ("3600mL", "60を そのまま かけた")],
  "1こ分は 600 ÷ 10 = 60mL。\n6こ分で 60 × 6 = 360mL。\n（600 × 0.6 = 360 でも 同じ）\nこたえ 360mL", "1こ分は 何mLかな。何こ分 ぬって あるかな。", f=figs.tape(10, 6), val=D(600)*D('0.6'))
Q(1, "5年生は 200人です。その 25% は 何人ですか。", "50人",
  [("5000人", "25% を 0.25 に 直さず、25を かけた"), ("5人", "25% を 0.025 に 直した"), ("8人", "200 ÷ 25 を 計算した")],
  "25% ＝ 0.25 なので 200 × 0.25 = 50。\nこたえ 50人", "25% は 小数で いくつかな。", val=D(200)*D('0.25'))
Q(1, "定員 50人の バスに、定員の 80% の 人が 乗って います。乗客は 何人ですか。", "40人",
  [("4000人", "80% を 0.8 に 直さず、80を かけた"), ("4人", "80% を 0.08 に 直した"), ("63人", "50 ÷ 0.8 を 計算した")],
  "80% ＝ 0.8 なので 50 × 0.8 = 40。\nこたえ 40人", "もとにする量は 定員の 50人だよ。", val=D(50)*D('0.8'))
# ---- 段階2
Q(2, "ある 町の 人口は 360人です。その 25% が 子どもです。子どもは 何人ですか。", "90人",
  [("9000人", "25% を 0.25 に 直さず、25を かけた"), ("14.4人", "360 ÷ 25 を 計算した"), ("9人", "25% を 0.025 に 直した")],
  "25% ＝ 0.25\n360 × 0.25 = 90\nこたえ 90人", "もとにする量は 360人。25% は 小数で いくつかな。", val=D(360)*D('0.25'))
Q(2, "定員 50人の バスに、定員の 140% の 人が 乗って しまいました。乗客は 何人ですか。", "70人",
  [("7000人", "140% を 1.4 に 直さず、140を かけた"), ("7人", "140% を 0.14 に 直した"), ("64人", "50 に 14を たした")],
  "140% ＝ 1.4\n50 × 1.4 = 70\nこたえ 70人", "100% より 大きい とき、わりあいは 1より 大きい 数だよ。", val=D(50)*D('1.4'))
Q(2, "広さ 90m² の 畑の 35% に、トマトを うえました。トマトの 畑は 何m² ですか。", "31.5m²",
  [("3150m²", "35% を 0.35 に 直さず、35を かけた"), ("3.15m²", "35% を 0.035 に 直した"), ("257m²", "90 ÷ 0.35 を 計算した")],
  "35% ＝ 0.35\n90 × 0.35 = 31.5\nこたえ 31.5m²", "もとにする量は 畑ぜんたいの 90m² だよ。", val=D(90)*D('0.35'))
Q(2, "定員 80人の バスに、歩合で 6わり5ぶ の 人が 乗って います。乗客は 何人ですか。（6わり5ぶ ＝ 0.65）", "52人",
  [("5.2人", "0.65 を 0.065 に 直した"), ("520人", "6.5 を かけた"), ("123人", "80 ÷ 0.65 を 計算した")],
  "80 × 0.65 = 52\nこたえ 52人", "6わり5ぶは 0.65 だよ。もとにする量に かけよう。", val=D(80)*D('0.65'))
Q(2, "水が 2.5L あります。その 40% は 何Lですか。", "1L",
  [("100L", "40% を 0.4 に 直さず、40を かけた"), ("0.1L", "40% を 0.04 に 直した"), ("6.25L", "2.5 ÷ 0.4 を 計算した")],
  "40% ＝ 0.4\n2.5 × 0.4 = 1\nこたえ 1L", "40% は 小数で 0.4 だよ。小数の かけ算を しよう。", val=D('2.5')*D('0.4'))
# ---- 段階3
Q(3, "ピヨは 1200円 もって います。その 35% で 本を 買いました。本の ねだんは いくらですか。", "420円",
  [("780円", "のこりの お金を 答えた"), ("42000円", "35% を 0.35 に 直さず、35を かけた"), ("4200円", "35% を 3.5 に 直した")],
  "もとにする量は 1200円。\n1200 × 0.35 = 420\nこたえ 420円", "本の ねだんは、もっていた お金の 35% だよ。", val=D(1200)*D('0.35'))
Q(3, "ジュースが 200mL あります。ピヨは その 40%、先生は その 35% を 飲みました。2人 あわせて 何mL 飲みましたか。", "150mL",
  [("80mL", "ピヨが 飲んだ ぶんだけ 答えた"), ("10mL", "2人の ちがいを 求めた"), ("50mL", "のこりを 答えた")],
  "ピヨ：200 × 0.4 = 80mL\n先生：200 × 0.35 = 70mL\n80 + 70 = 150\nこたえ 150mL", "ピヨと 先生の 飲んだ ぶんを べつべつに 求めよう。", val=D(200)*D('0.4')+D(200)*D('0.35'))
Q(3, "定員 60人の バスに、定員の 45% の 人が 乗って います。乗客の 人数を 求める しきは どれですか。", "60 × 0.45",
  [("60 × 45", "45% を 小数に 直して いない"), ("60 ÷ 0.45", "わり算で 求めると 思った"), ("45 ÷ 60", "わりあいを 求める しきに なって いる")],
  "乗客は 比べる量。比べる量 ＝ もとにする量 × わりあい。\nもとにする量は 60人、わりあいは 45% ＝ 0.45。\nこたえ 60 × 0.45", "比べる量は、もとにする量 × わりあいで 求めたね。")
Q(3, "ある 町の 人口は 8000人で、その 15% が 子どもです。おとなは 何人ですか。", "6800人",
  [("1200人", "子どもの 人数を 答えた"), ("120000人", "15% を 15 として かけた"), ("7985人", "8000から 15を ひいた")],
  "子ども：8000 × 0.15 = 1200人\nおとな：8000 − 1200 = 6800人\nこたえ 6800人", "まず 子どもの 人数を 求めよう。おとなは のこりだよ。", val=D(8000)-D(8000)*D('0.15'))
Q(3, "ピヨは 「240人の 30% は 240 × 30 = 7200人」と しました。ただしい 答えは 何人ですか。", "72人",
  [("7200人", "ピヨの まちがった 答え"), ("8人", "240 ÷ 30 を 計算した"), ("270人", "240に 30を たした")],
  "30% ＝ 0.3 に 直して かける。\n240 × 0.3 = 72\nこたえ 72人", "もとの 240人より 7200人が 大きいのは おかしいね。", val=D(240)*D('0.3'))
