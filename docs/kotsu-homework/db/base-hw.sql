-- ── 内部の関数（本番の定義のまま。本番では、すべて security invoker・search_path 指定なし・postgres だけが実行できる） ──
create or replace function kotsu._h(p text) returns text language sql immutable
as $function$ select encode(extensions.digest(coalesce(p, ''), 'sha256'), 'hex') $function$;

create or replace function kotsu._err(p_code text) returns void language plpgsql
as $function$ begin raise exception using errcode = 'P0001', message = p_code; end $function$;

create or replace function kotsu._clip(p text, n integer) returns text language sql immutable
as $function$ select left(coalesce(p, ''), n) $function$;

create or replace function kotsu._audit(p_org uuid, p_actor uuid, p_role text, p_action text, p_target text default ''::text, p_detail jsonb default '{}'::jsonb)
returns void language sql
as $function$ insert into kotsu.audit (org_id, actor, actor_role, action, target, detail) values (p_org, p_actor, p_role, p_action, coalesce(p_target, ''), coalesce(p_detail, '{}'::jsonb)) $function$;

create or replace function kotsu._rate_clear(p_k text) returns void language sql
as $function$ delete from kotsu.rate where k = p_k $function$;

create or replace function kotsu._rate_hit(p_k text, p_win interval) returns void language sql
as $function$
  insert into kotsu.rate (k, n, since) values (p_k, 1, now())
  on conflict (k) do update set
    n = case when kotsu.rate.since < now() - p_win then 1 else kotsu.rate.n + 1 end,
    since = case when kotsu.rate.since < now() - p_win then now() else kotsu.rate.since end
$function$;

create or replace function kotsu._rate_locked(p_k text, p_lim integer, p_win interval) returns boolean language sql stable
as $function$ select exists (select 1 from kotsu.rate r where r.k = p_k and r.n >= p_lim and r.since > now() - p_win) $function$;

create or replace function kotsu._who(p_token text) returns kotsu.users language plpgsql
as $function$
declare s kotsu.sessions; u kotsu.users;
begin
  if p_token is null or length(p_token) < 20 then perform kotsu._err('auth'); end if;
  select * into s from kotsu.sessions where token_hash = kotsu._h(p_token) and kind = 'user';
  if not found or s.expires_at < now() then perform kotsu._err('auth'); end if;
  select * into u from kotsu.users where id = s.user_id;
  if not found or not u.active then perform kotsu._err('auth'); end if;
  if not exists (select 1 from kotsu.orgs o where o.id = u.org_id and o.active) then perform kotsu._err('org_off'); end if;
  if s.last_seen < now() - interval '10 minutes' then
    update kotsu.sessions set last_seen = now(),
      expires_at = greatest(expires_at, now() + case when u.role = 'student' then interval '180 days' else interval '30 days' end)
    where token_hash = s.token_hash;
  end if;
  return u;
end $function$;

create or replace function kotsu._staff(p_token text) returns kotsu.users language plpgsql
as $function$
declare u kotsu.users := kotsu._who(p_token);
begin
  if u.role not in ('admin', 'teacher') then perform kotsu._err('role'); end if;
  return u;
end $function$;

create or replace function kotsu._admin(p_token text) returns kotsu.users language plpgsql
as $function$
declare u kotsu.users := kotsu._who(p_token);
begin
  if u.role <> 'admin' then perform kotsu._err('role'); end if;
  return u;
end $function$;

create or replace function kotsu._same_org(t kotsu.users, p_user uuid) returns kotsu.users language plpgsql
as $function$
declare x kotsu.users;
begin
  select * into x from kotsu.users where id = p_user and org_id = t.org_id;
  if not found then perform kotsu._err('not_found'); end if;
  return x;
end $function$;

create or replace function kotsu._can_class(t kotsu.users, p_class uuid) returns boolean language sql stable
as $function$
  select exists (select 1 from kotsu.classes c where c.id = p_class and c.org_id = t.org_id
    and (t.role = 'admin' or exists (select 1 from kotsu.class_teachers ct where ct.class_id = c.id and ct.user_id = t.id)))
$function$;

create or replace function kotsu._can_see(t kotsu.users, p_student uuid) returns boolean language sql stable
as $function$
  select case
    when t.role = 'admin' then exists (select 1 from kotsu.users s where s.id = p_student and s.org_id = t.org_id and s.role = 'student')
    when t.role = 'teacher' then exists (
      select 1 from kotsu.class_students cs
      join kotsu.class_teachers ct on ct.class_id = cs.class_id
      join kotsu.classes c on c.id = cs.class_id
      where cs.user_id = p_student and ct.user_id = t.id and c.org_id = t.org_id and not c.archived)
    else false end
$function$;

create or replace function kotsu._last(st kotsu.states) returns timestamptz language sql immutable
as $function$
  select case when (st.summary->>'last') ~ '^[0-9]{10,14}$' and (st.summary->>'last')::bigint > 0
    then to_timestamp((st.summary->>'last')::bigint / 1000.0) else st.updated_at end
$function$;

create or replace function kotsu._user_json(u kotsu.users) returns jsonb language sql stable
as $function$
  select jsonb_build_object('id', u.id, 'role', u.role, 'login', u.login_id, 'nick', u.nick, 'name_enc', u.name_enc,
    'grade', u.grade, 'active', u.active, 'last_login_at', u.last_login_at, 'created_at', u.created_at)
$function$;

create or replace function kotsu._org_json(o kotsu.orgs) returns jsonb language sql stable
as $function$
  select jsonb_build_object('id', o.id, 'code', o.code, 'name', o.name, 'kind', o.kind, 'active', o.active,
    'roster', case when o.roster_check is null then null else jsonb_build_object('salt', o.roster_salt, 'check', o.roster_check, 'iter', o.roster_iter, 'at', o.roster_at) end,
    'fb_named', coalesce(o.fb_named, false))
$function$;

create or replace function kotsu._student_row(s kotsu.users, p_no integer default null::integer) returns jsonb language sql stable
as $function$
  select kotsu._user_json(s) || jsonb_build_object('no', p_no,
    'summary', coalesce(st.summary, '{}'::jsonb), 'updated_at', st.updated_at, 'rev', st.rev, 'size', st.size)
  from (select 1) one left join kotsu.states st on st.user_id = s.id
$function$;

-- ── 公開の関数（本番の定義のまま。security definer・search_path=kotsu, extensions, public） ──
create or replace function kotsu.login(p_org text, p_login text, p_pass text) returns jsonb
language plpgsql security definer set search_path to 'kotsu', 'extensions', 'public'
as $function$
declare o kotsu.orgs; u kotsu.users; k text; ko text; tok text;
begin
  k := 'L:' || upper(trim(coalesce(p_org, ''))) || ':' || lower(trim(coalesce(p_login, '')));
  ko := 'O:' || upper(trim(coalesce(p_org, '')));
  if kotsu._rate_locked(k, 10, interval '15 minutes') or kotsu._rate_locked(ko, 200, interval '15 minutes') then
    return jsonb_build_object('error', 'locked');
  end if;
  select * into o from kotsu.orgs where code = upper(trim(coalesce(p_org, '')));
  if found then
    select * into u from kotsu.users where org_id = o.id and login_id = lower(trim(coalesce(p_login, '')));
  end if;
  if u.id is null then
    perform extensions.crypt(coalesce(p_pass, ''), extensions.gen_salt('bf', 8));   -- いない ID でも、同じくらい時間をかける
  end if;
  if u.id is null or not u.active or u.pass_hash <> extensions.crypt(coalesce(p_pass, ''), u.pass_hash) then
    perform kotsu._rate_hit(k, interval '15 minutes');
    perform kotsu._rate_hit(ko, interval '15 minutes');
    return jsonb_build_object('error', 'bad');
  end if;
  if not o.active then return jsonb_build_object('error', 'org_off'); end if;
  perform kotsu._rate_clear(k);
  tok := encode(extensions.gen_random_bytes(24), 'hex');
  insert into kotsu.sessions (token_hash, user_id, kind, expires_at)
    values (kotsu._h(tok), u.id, 'user', now() + case when u.role = 'student' then interval '180 days' else interval '30 days' end);
  delete from kotsu.sessions where user_id = u.id and token_hash in (
    select token_hash from kotsu.sessions where user_id = u.id order by last_seen desc offset 10);
  update kotsu.users set last_login_at = now() where id = u.id;
  if u.role <> 'student' then perform kotsu._audit(o.id, u.id, u.role, 'login'); end if;
  return jsonb_build_object('ok', true, 'token', tok, 'user', kotsu._user_json(u), 'org', kotsu._org_json(o));
end $function$;

create or replace function kotsu.me(p_token text) returns jsonb
language plpgsql security definer set search_path to 'kotsu', 'extensions', 'public'
as $function$
declare u kotsu.users := kotsu._who(p_token); o kotsu.orgs;
begin
  select * into o from kotsu.orgs where id = u.org_id;
  return jsonb_build_object('ok', true, 'user', kotsu._user_json(u), 'org', kotsu._org_json(o),
    'state', (select jsonb_build_object('rev', s.rev, 'updated_at', s.updated_at) from kotsu.states s where s.user_id = u.id));
end $function$;

create or replace function kotsu.t_home(p_token text) returns jsonb
language plpgsql security definer set search_path to 'kotsu', 'extensions', 'public'
as $function$
declare t kotsu.users := kotsu._staff(p_token); o kotsu.orgs; v jsonb;
begin
  select * into o from kotsu.orgs where id = t.org_id;
  select coalesce(jsonb_agg(x order by x->>'name'), '[]'::jsonb) into v from (
    select jsonb_build_object('id', c.id, 'name', c.name, 'year', c.year,
      'n', (select count(*) from kotsu.class_students cs join kotsu.users s on s.id = cs.user_id and s.active where cs.class_id = c.id),
      'active7', (select count(*) from kotsu.class_students cs join kotsu.states st on st.user_id = cs.user_id where cs.class_id = c.id and kotsu._last(st) > now() - interval '7 days'),
      'mine', exists (select 1 from kotsu.class_teachers ct where ct.class_id = c.id and ct.user_id = t.id),
      'teachers', (select coalesce(jsonb_agg(jsonb_build_object('id', u2.id, 'nick', u2.nick) order by u2.nick), '[]'::jsonb)
                   from kotsu.class_teachers ct join kotsu.users u2 on u2.id = ct.user_id where ct.class_id = c.id)) as x
    from kotsu.classes c
    where c.org_id = t.org_id and not c.archived
      and (t.role = 'admin' or exists (select 1 from kotsu.class_teachers ct where ct.class_id = c.id and ct.user_id = t.id))
  ) q;
  return jsonb_build_object('ok', true, 'me', kotsu._user_json(t), 'org', kotsu._org_json(o), 'classes', v);
end $function$;

create or replace function kotsu.t_class(p_token text, p_class uuid) returns jsonb
language plpgsql security definer set search_path to 'kotsu', 'extensions', 'public'
as $function$
declare t kotsu.users := kotsu._staff(p_token); c kotsu.classes; v jsonb;
begin
  if not kotsu._can_class(t, p_class) then perform kotsu._err('not_found'); end if;
  select * into c from kotsu.classes where id = p_class;
  select coalesce(jsonb_agg(kotsu._student_row(s, cs.no) order by cs.no nulls last, s.login_id), '[]'::jsonb) into v
    from kotsu.class_students cs join kotsu.users s on s.id = cs.user_id
    where cs.class_id = p_class and s.role = 'student';
  return jsonb_build_object('ok', true, 'class', jsonb_build_object('id', c.id, 'name', c.name, 'year', c.year), 'students', v);
end $function$;

create or replace function kotsu.t_student(p_token text, p_student uuid) returns jsonb
language plpgsql security definer set search_path to 'kotsu', 'extensions', 'public'
as $function$
declare t kotsu.users := kotsu._staff(p_token); s kotsu.users; st kotsu.states;
begin
  if not kotsu._can_see(t, p_student) then perform kotsu._err('not_found'); end if;
  select * into s from kotsu.users where id = p_student;
  select * into st from kotsu.states where user_id = p_student;
  return jsonb_build_object('ok', true, 'student', kotsu._user_json(s),
    'state', st.state, 'summary', coalesce(st.summary, '{}'::jsonb), 'rev', st.rev, 'updated_at', st.updated_at,
    'classes', (select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'name', c.name, 'no', cs.no) order by c.name), '[]'::jsonb)
                from kotsu.class_students cs join kotsu.classes c on c.id = cs.class_id where cs.user_id = p_student and not c.archived),
    'marks', '{}'::jsonb);   -- 本番は kotsu.marks から集める。marks の表は写していないので、ここでは空
end $function$;

create or replace function kotsu.state_push(p_token text, p_state jsonb, p_summary jsonb, p_base integer, p_ver text default ''::text, p_force boolean default false) returns jsonb
language plpgsql security definer set search_path to 'kotsu', 'extensions', 'public'
as $function$
declare u kotsu.users := kotsu._who(p_token); cur kotsu.states; sz int; n_old int; n_new int;
begin
  if u.role <> 'student' then perform kotsu._err('role'); end if;
  if p_state is null or jsonb_typeof(p_state) <> 'object' then perform kotsu._err('bad_state'); end if;
  sz := octet_length(p_state::text);
  if sz > 2000000 then perform kotsu._err('too_big'); end if;
  if p_summary is null or jsonb_typeof(p_summary) <> 'object' or octet_length(p_summary::text) > 30000 then perform kotsu._err('bad_summary'); end if;
  select * into cur from kotsu.states where user_id = u.id for update;
  if not found then
    insert into kotsu.states (user_id, state, summary, rev, size, app_ver) values (u.id, p_state, p_summary, 1, sz, kotsu._clip(p_ver, 40));
    return jsonb_build_object('ok', true, 'rev', 1);
  end if;
  if cur.rev <> coalesce(p_base, -1) and not coalesce(p_force, false) then
    return jsonb_build_object('conflict', true, 'rev', cur.rev, 'updated_at', cur.updated_at, 'n', coalesce((cur.summary->>'n')::int, 0));
  end if;
  n_old := coalesce((cur.summary->>'n')::int, 0);
  n_new := coalesce((p_summary->>'n')::int, 0);
  if coalesce(p_force, false) or n_new < n_old then     -- 上書きで問題数がへるときは、前のものを控えにのこす
    insert into kotsu.state_backups (user_id, state, summary, rev, reason)
      values (u.id, cur.state, cur.summary, cur.rev, case when coalesce(p_force, false) then 'force' else 'smaller' end);
    delete from kotsu.state_backups where user_id = u.id and id not in (
      select id from kotsu.state_backups where user_id = u.id order by created_at desc limit 5);
  end if;
  update kotsu.states set state = p_state, summary = p_summary, rev = cur.rev + 1, size = sz, app_ver = kotsu._clip(p_ver, 40), updated_at = now()
    where user_id = u.id;
  return jsonb_build_object('ok', true, 'rev', cur.rev + 1);
end $function$;

