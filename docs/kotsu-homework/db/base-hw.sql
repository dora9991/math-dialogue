-- ── 表（本番の列・型・既定値・制約・索引・外部キーのとおり） ──
create table kotsu.orgs (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  name text not null,
  kind text not null default 'juku' check (kind = any (array['juku','school','other'])),
  active boolean not null default true,
  roster_salt text,
  roster_check text,
  roster_iter integer not null default 600000,
  roster_at timestamptz,
  limits jsonb not null default '{"staff": 50, "students": 500}'::jsonb,
  note text not null default '',
  created_at timestamptz not null default now(),
  fb_named boolean not null default false
);

create table kotsu.users (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references kotsu.orgs(id) on delete cascade,
  role text not null check (role = any (array['admin','teacher','student'])),
  login_id text not null,
  pass_hash text not null,
  nick text not null default '',
  name_enc text,
  grade text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  last_login_at timestamptz,
  pass_set_at timestamptz not null default now(),
  unique (org_id, login_id)
);
create index users_org_role on kotsu.users using btree (org_id, role);

create table kotsu.sessions (
  token_hash text primary key,
  user_id uuid references kotsu.users(id) on delete cascade,
  kind text not null default 'user' check (kind = any (array['user','op'])),
  created_at timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  expires_at timestamptz not null
);
create index sessions_user on kotsu.sessions using btree (user_id);

create table kotsu.classes (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references kotsu.orgs(id) on delete cascade,
  name text not null,
  year integer,
  archived boolean not null default false,
  created_at timestamptz not null default now()
);

create table kotsu.class_teachers (
  class_id uuid not null references kotsu.classes(id) on delete cascade,
  user_id uuid not null references kotsu.users(id) on delete cascade,
  primary key (class_id, user_id)
);
create index class_teachers_user on kotsu.class_teachers using btree (user_id);

create table kotsu.class_students (
  class_id uuid not null references kotsu.classes(id) on delete cascade,
  user_id uuid not null references kotsu.users(id) on delete cascade,
  no integer,
  primary key (class_id, user_id)
);
create index class_students_user on kotsu.class_students using btree (user_id);

create table kotsu.states (
  user_id uuid primary key references kotsu.users(id) on delete cascade,
  state jsonb not null,
  summary jsonb not null default '{}'::jsonb,
  rev integer not null default 1,
  size integer not null default 0,
  app_ver text not null default '',
  updated_at timestamptz not null default now()
);

create table kotsu.state_backups (
  id bigint generated by default as identity primary key,
  user_id uuid not null references kotsu.users(id) on delete cascade,
  state jsonb not null,
  summary jsonb not null default '{}'::jsonb,
  rev integer not null,
  reason text not null default '',
  created_at timestamptz not null default now()
);
create index state_backups_user on kotsu.state_backups using btree (user_id, created_at desc);

create table kotsu.audit (
  id bigint generated by default as identity primary key,
  org_id uuid references kotsu.orgs(id) on delete cascade,
  actor uuid,
  actor_role text not null,
  action text not null,
  target text not null default '',
  detail jsonb not null default '{}'::jsonb,
  at timestamptz not null default now()
);
create index audit_org on kotsu.audit using btree (org_id, at desc);

create table kotsu.rate (
  k text primary key,
  n integer not null default 0,
  since timestamptz not null default now()
