create or replace function kotsu.a_class_delete(p_token text, p_class uuid) returns jsonb
language plpgsql security definer set search_path to 'kotsu', 'extensions', 'public'
as $function$
declare a kotsu.users := kotsu._admin(p_token); c kotsu.classes;
begin
  select * into c from kotsu.classes where id = p_class and org_id = a.org_id;
  if not found then perform kotsu._err('not_found'); end if;
  delete from kotsu.classes where id = p_class;     -- 生徒・学習の記録は消えない（クラスからはずれるだけ）
  perform kotsu._audit(a.org_id, a.id, 'admin', 'class_delete', c.name);
  return jsonb_build_object('ok', true);
end $function$;

create or replace function kotsu.a_user_delete(p_token text, p_user uuid) returns jsonb
language plpgsql security definer set search_path to 'kotsu', 'extensions', 'public'
as $function$
declare a kotsu.users := kotsu._admin(p_token); x kotsu.users := kotsu._same_org(a, p_user);
begin
  if x.id = a.id then perform kotsu._err('self'); end if;
  if x.active then perform kotsu._err('stop_first'); end if;
  delete from kotsu.users where id = x.id;
  perform kotsu._audit(a.org_id, a.id, 'admin', 'user_delete', x.login_id, jsonb_build_object('role', x.role));
  return jsonb_build_object('ok', true);
end $function$;

-- ── 関数の権限（本番の proacl のとおり）──
--   内部（_ではじまる）：{postgres=X/postgres}（public からも anon からも実行できない）
--   公開：{postgres=X/postgres,anon=X/postgres,authenticated=X/postgres}
do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'kotsu' loop
    execute format('revoke all on function %s from public', f.sig);
    if left(f.proname, 1) <> '_' then
      execute format('grant execute on function %s to anon, authenticated', f.sig);
    end if;
  end loop;
end $$;
