def dot(u, v): return u[0]*v[0] + u[1]*v[1]
def cross(u, v): return u[0]*v[1] - u[1]*v[0]
def vec(p, q): return (q[0]-p[0], q[1]-p[1])
def para(l1, l2): return cross(vec(*l1), vec(*l2)) == 0
def perp(l1, l2): return dot(vec(*l1), vec(*l2)) == 0
def sq(p, q): return (q[0]-p[0])**2 + (q[1]-p[1])**2
def edges(pts): return [(pts[i], pts[(i+1) % len(pts)]) for i in range(len(pts))]
def npar(pts):
    e = edges(pts); return (1 if para(e[0], e[2]) else 0) + (1 if para(e[1], e[3]) else 0)
def parpairs(pts):
    e = edges(pts); return [i for i, j in ((0, 2), (1, 3)) if para(e[i], e[j])]
def is_para4(pts): return npar(pts) == 2
def is_rhombus(pts):
    e = edges(pts); return len({sq(*x) for x in e}) == 1 and npar(pts) == 2
def is_rect(pts):
    e = edges(pts); return npar(pts) == 2 and all(perp(e[i], e[(i+1) % 4]) for i in range(4))
def hand_angle(h, m):
    a = abs((h % 12) * 30 + m * 0.5 - m * 6) % 360
    return min(a, 360 - a)
def fourth(a, b, c): return (a[0]+c[0]-b[0], a[1]+c[1]-b[1])

