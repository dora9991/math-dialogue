from common import *
from itertools import permutations as PM, combinations as CB, product as PR

def A(t, v=None): return (t, t if v is None else v)
def n(x): return f'{x}通り'
def digits(cards, k, nozero=True):
    out = []
    for p in PM(cards, k):
        if nozero and p[0] == 0: continue
        out.append(int(''.join(map(str, p))))
    return out

