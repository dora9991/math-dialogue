def ratio_of(p, q):
    """図形 p に 対する q の 拡大の 倍（よこ・たて が 同じ 倍の ときだけ 値を 返す。ちがえば None）"""
    (w1, h1), (w2, h2) = span(p), span(q)
    if Fr(w2, w1) == Fr(h2, h1):
        return Fr(w2, w1)
    return None


def disp(dx, dy):
    """ほうがん紙の 進み方（y は 下向き）を ことばに する"""
    h = f"右へ {dx}マス" if dx >= 0 else f"左へ {-dx}マス"
    v = f"上へ {-dy}マス" if dy <= 0 else f"下へ {dy}マス"
    return f"{h}、{v}"


