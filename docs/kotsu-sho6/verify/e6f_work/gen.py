def fmt(x):
    if isinstance(x, str): return x
    if abs(x - round(x)) < 1e-9: return str(int(round(x)))
    return ('%.4f' % x).rstrip('0').rstrip('.')

def rank_class(edges, c, r):
    cum = 0
    for i, k in enumerate(c):
        cum += k
        if r <= cum: return (edges[i], edges[i + 1])
    return None

ENV = dict(mean=st.mean, median=st.median, mode=st.mode, Fraction=Fraction, sorted=sorted, sum=sum,
           len=len, max=max, min=min, abs=abs, round=round, rank_class=rank_class, range=range, list=list, zip=zip, True_=True)
def ev(expr, v):
    if not isinstance(expr, str): return expr
    g = dict(ENV); g.update(v)
    return eval(expr, {'__builtins__': {}, **g})

def j(d, u='', sep='、'): return sep.join(fmt(x) + u for x in d)
def cl(lo, hi, u='m'): return f'{lo}{u} 以上 {hi}{u} 未満'

LESSONS = {}
class Lesson:
    def __init__(self, lid, code, no, seed):
        self.id = lid; self.u = f'E6-T{code}'; self.s = f'{self.u}-{no:02d}'
        self.items = []; self.meta = {}
        self.rng = random.Random(seed)
        pos = [0, 1, 2, 3] * 5; self.rng.shuffle(pos); self.pos = pos
        self.cnt = {1: 0, 2: 0, 3: 0, 4: 0}
        LESSONS[lid] = self
    def _add(self, d, q, choices, e, h, f, meta):
        self.cnt[d] += 1; n = self.cnt[d]
        qid = f'{self.id}-L{d}-{n:02d}'
        idx = (d - 1) * 5 + (n - 1); p = self.pos[idx]
        # choices: list; first = correct, rest wrong
        cor, wr = choices[0], choices[1:]
        assert len(wr) == 3
        order = list(wr); order.insert(p, cor)
        c = []
        for k, (t, w) in enumerate(order):
            o = {'t': t}
            if k == p: o['k'] = 1
            elif w: o['w'] = w
            c.append(o)
        it = {'id': qid, 'u': self.u, 's': self.s, 'l': self.id, 'd': d, 'q': q, 'c': c, 'e': e, 'h': h}
        if f: it['f'] = f
        self.items.append(it); meta['id'] = qid; self.meta[qid] = meta
        assert sum(1 for x in c if x.get('w')) >= 2, qid
    def num(self, d, q, expr, v, unit, wrongs, e, h, f=None, figcheck=None):
        val = ev(expr, v)
        cor = (fmt(val) + unit, None)
        wr = []
        for x, w in wrongs:
            xv = ev(x, v); assert abs(xv - val) > 1e-9, (q, x)
            wr.append((fmt(xv) + unit, w))
        texts = [t for t, _ in [cor] + wr]; assert len(set(texts)) == 4, (q, texts)
        self._add(d, q, [cor] + wr, e, h, f, {'kind': 'num', 'v': v, 'expr': expr, 'unit': unit,
                  'wrongs': [x for x, _ in wrongs], 'figcheck': figcheck})
    def truth(self, d, q, choices, v, e, h, f=None, figcheck=None):
        # choices: (text, expr, why) ; first must be True and the others False
        res = [bool(ev(x, v)) for _, x, _ in choices]
        assert res == [True, False, False, False], (q, res)
        self._add(d, q, [(t, w) for t, _, w in choices], e, h, f,
                  {'kind': 'truth', 'v': v, 'choices': [[t, x] for t, x, _ in choices], 'figcheck': figcheck})
    def save(self):
        assert all(self.cnt[d] == 5 for d in self.cnt), self.cnt
        os.makedirs(f'{BASE}/out/e6f', exist_ok=True)
        json.dump(self.items, open(f'{BASE}/out/e6f/{self.id}.json', 'w'), ensure_ascii=False, indent=1)

