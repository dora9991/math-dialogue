# e1f: 問題を つくって（JSON を かく）、全問「問題 → 計算した答え」を 一覧に して 正解と 突き合わせる
import sys, json, re, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE)); import figs
OUT = os.path.join(HERE, 'e1f')
LES = {}   # lesson -> list
ROWS = []  # (id, q, calc, ans)
CUR = {}

def lesson(lid, code, no):
    CUR.update(l=lid, code=code, no=no, items=[], seen=set())
    LES[lid] = CUR['items']

def Q(d, q, ans, wrongs, e, h, f=None, calc=None):
    """ans: 正解の文字。wrongs: [(文字, w or None)] 3つ。calc: 答えを 計算する python 式（文字に なる）"""
    items = CUR['items']; i = len(items); n = i % 5 + 1
    assert d == i // 5 + 1, (CUR['l'], i, d)
    assert len(wrongs) == 3, (CUR['l'], q, wrongs)
    pos = (i * 3 + i // 4) % 4
    ch = [{'t': t, **({'w': w} if w else {})} for t, w in wrongs]
    ch.insert(pos, {'t': ans, 'k': 1})
    ts = [c['t'] for c in ch]; assert len(set(ts)) == 4, (CUR['l'], q, ts)
    if calc is not None:
        v = str(eval(calc)); assert v == ans, (CUR['l'], q, calc, v, ans)
    for t, _ in wrongs:
        if calc is not None: assert t != str(eval(calc)), (q, t)
    # しき「a ± b = □」を q から もういちど けいさん
    m = re.search(r'(\d+) ([+−]) (\d+) = □', q)
    if m and not re.search(r'□ [+−]|[+−] □', q):
        a, op, b = int(m[1]), m[2], int(m[3]); assert str(a + b if op == '+' else a - b) == ans, (q, ans)
    key = q + '|' + '|'.join(sorted(ts)); assert key not in CUR['seen'] and key not in ALLSEEN, ('dup', q); CUR['seen'].add(key); ALLSEEN.add(key)
    code = CUR['code']; no = '%02d' % CUR['no']
    o = {'id': f"{CUR['l']}-L{d}-{n:02d}", 'u': f'E1-T{code}', 's': f'E1-T{code}-{no}', 'l': CUR['l'], 'd': d, 'q': q, 'c': ch, 'e': e, 'h': h}
    if f: o['f'] = f
    items.append(o); ROWS.append((o['id'], q.replace('\n', ' '), calc or '(文)', ans))
ALLSEEN = set()

def W(*pairs): return list(pairs)

# ---- くりかえし つかう まちがい 作り -------------------------------------
def pick(cands, ans, k=3, shift=0):
    out = []; seen = {str(ans)}
    cs = cands[shift % len(cands):] + cands[:shift % len(cands)]
    for t, w in cs:
        if str(t) in seen or (isinstance(t, int) and (t < 0 or t > 100)): continue
        seen.add(str(t)); out.append((str(t), w))
    assert len(out) >= k, (ans, cands); return out[:k]
def w_add10(a, b, s=0):
    r = a + b
    return pick([(r // 10, '10の ぼうの かずだけ こたえた'), (a + b // 10, f'{b}を {b // 10}と かんがえた'), (r + 10, '10の ぼうを 1ぽん おおく かぞえた'), (r - 10, '10の ぼうを 1ぽん すくなく かぞえた')], r, shift=s)
def w_sub10(a, b, s=0):
    r = a - b
    return pick([(r // 10, 'のこりの ぼうの かずだけ こたえた'), (a + b, 'たしざんを してしまった'), (r + 10, '10の ぼうを 1ぽん おおく かぞえた'), (a - b // 10, f'{b}を {b // 10}と かんがえた'), (r - 10, '10の ぼうを 1ぽん すくなく かぞえた')], r, shift=s)
def w_add1(a, b, s=0):
    t, o = divmod(a, 10); r = a + b
    return pick([((t + b) * 10 + o, 'ぼうに ばらを たしてしまった'), (o + b, 'ばらの かずだけ たした'), (r + 10, '10の ぼうを 1ぽん おおく かぞえた'), (r + 1, 'かぞえる とき 1つ おおく かぞえた'), (r - 1, 'かぞえる とき 1つ すくなく かぞえた')], r, shift=s)
def w_sub1(a, b, s=0):
    t, o = divmod(a, 10); r = a - b
    return pick([((t - b) * 10 + o, 'ぼうから ひいてしまった'), (a + b, 'たしざんを してしまった'), (o - b, 'ばらの かずだけ こたえた'), (r + 1, 'かぞえる とき 1つ おおく かぞえた'), (r - 1, 'かぞえる とき 1つ すくなく かぞえた'), (r + 10, '10の ぼうを 1ぽん おおく かぞえた')], r, shift=s)
def sk(a, op, b): return f'{a} {op} {b} = □　□に はいる かずは？'

def finish():
    os.makedirs(OUT, exist_ok=True)
    for lid, items in LES.items():
        assert len(items) == 20, (lid, len(items))
        json.dump(items, open(f'{OUT}/{lid}.json', 'w'), ensure_ascii=False, indent=1)

