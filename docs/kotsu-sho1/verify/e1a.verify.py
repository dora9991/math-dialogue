bad = 0
def fail(i, m):
    global bad; bad += 1; print('  NG', i['id'], m)
for i in items:
    right = [c['t'] for c in i['c'] if c.get('k') == 1]
    wrong = [c['t'] for c in i['c'] if c.get('k') != 1]
    calc = CALC[i['id']]
    ind = None
    q = i['q']
    # (1) 「A は B と □」「A は □と B」を、もういちど べつに とく
    m = re.fullmatch(r'(\d+)は (\d+)と □。□に はいる かずは？', q)
    if m: ind = str(int(m.group(1)) - int(m.group(2)))
    m = re.fullmatch(r'(\d+)は □と (\d+)。□に はいる かずは？', q)
    if m: ind = str(int(m.group(1)) - int(m.group(2)))
    # (2) 図の しるしを かぞえる（「●は いくつ」「▲は」「■は」の もんだい）
    m = re.match(r'([●▲■])は いくつ', q)
    if m and i.get('f'):
        n = {'●': len(re.findall(r'class="fg-dot"', i['f'])), '▲': len(re.findall(r'<path d="M[\d.]+ [\d.]+ l10 18', i['f'])),
             '■': len(re.findall(r'<rect x="[\d.]+" y="[\d.]+" width="18"', i['f']))}[m.group(1)]
        ind = f'{n}こ'
    if ind is not None:
        ind_t = ind if ind in right or ind in wrong else None
        if ind_t is None and not any(ind == r.rstrip('こ') for r in right): fail(i, f'べつの けいさん {ind} が せんたくしに ない')
        if right[0].rstrip('こ') != ind.rstrip('こ'): fail(i, f'べつの けいさん {ind} と 正解 {right[0]} が ちがう')
    if len(right) != 1: fail(i, 'せいかいが 1つでない')
    if right[0] != calc: fail(i, f'けいさん {calc} と 正解 {right[0]} が ちがう')
    if calc in wrong: fail(i, 'まちがいの せんたくしに 正解と おなじものが ある')
    print(f"{i['id']}  {q}  ->  {calc}   (正解の せんたくし: {right[0]})")
print('NG', bad, '件' if bad else '件  全問 いっち')
sys.exit(1 if bad else 0)
