def _pos(l):
    r = random.Random(l); p = [0, 1, 2, 3] * 5; r.shuffle(p); return p

def _add(l, d, q, correct, wrongs, e, h, f, calc):
    lst = DB.setdefault(l, [])
    n = sum(1 for x in lst if x['d'] == d) + 1
    idx = len(lst)
    assert len(wrongs) == 3, (l, q, wrongs)
    texts = [correct] + [w[0] for w in wrongs]
    assert len(set(texts)) == 4, (l, q, texts)
    assert calc == correct, (l, q, calc, correct)
    pos = _pos(l)[idx]
    ch = [{'t': t, **({'w': w} if w else {})} for t, w in wrongs]
    ch.insert(pos, {'t': correct, 'k': 1})
    code = 'C'
    no = str(LESSONS[l] if l.startswith('awase') else LESSONS[l]).zfill(2)
    it = {'id': f'{l}-L{d}-0{n}', 'u': 'E1-T' + CODE_OF[l][0], 's': f"E1-T{CODE_OF[l][0]}-{str(CODE_OF[l][1]).zfill(2)}", 'l': l, 'd': d, 'q': q, 'c': ch, 'e': e, 'h': h}
    if f: it['f'] = f
    lst.append(it)
    LOG.append((it['id'], q, calc, correct))

