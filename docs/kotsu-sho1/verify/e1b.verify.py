def T(l, d, q, correct, wrongs, e, h, f=None, calc=None):
    """文字の選択肢。calc＝計算で出した正解（文字）"""
    _add(l, d, q, correct, wrongs, e, h, f, correct if calc is None else calc)

def N(l, d, q, val, fmt, cands, e, h, f=None, calc=None):
    """数の選択肢。val＝正解の数（計算した値）。cands＝まちがいの候補（数, w）の じゅん。"""
    if calc is not None: assert calc == val, (l, q, calc, val)
    ws = []; seen = {val}
    for v, w in cands:
        if v in seen or v < 0 or v > 10: continue
        seen.add(v); ws.append((fmt(v), w))
    ws = ws[:3]
    # w は 3つのうち 2つ以上
    _add(l, d, q, fmt(val), ws, e, h, f, fmt(val))

