      // 小テスト（1）（2）3人のならび方 6通り、A が真ん中は 2通り → 1/3　（3）4枚から 2枚の 2けた 12通り、奇数 6通り → 1/2　（4）3枚の硬貨が同じ面 2/8＝1/4
