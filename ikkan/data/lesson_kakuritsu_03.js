  const uni = lists => lists.length ? lists[0].map(t => [t, uni(lists.slice(1))]) : [];           // どの枝も同じ形の樹形図
  const seq = (xs, k) => k === 0 ? [] : xs.map(x => [x, seq(xs.filter(y => y !== x), k - 1)]);       // 同じものを2回使わない樹形図（k段）
  const TREE = (spec, o) => SVG((W, H, h) => {
    o = o || {};
    const norm = n => Array.isArray(n) ? { t: String(n[0]), ch: (n[1] || []).map(norm) } : { t: String(n), ch: [] };
    const roots = spec.map(norm), leaves = [];
    let D = 0;
    const walk = (n, d, path) => { n.d = d; n.path = path.concat(n.t); D = Math.max(D, d); if (!n.ch.length) leaves.push(n); n.ch.forEach(c => walk(c, d + 1, n.path)); };
    roots.forEach(r => walk(r, 0, []));
    const fs = o.fs || 3.2, top = o.heads ? 7 : 3, bot = 3, dy = Math.min(o.dyMax || 7, (H - top - bot) / leaves.length);
    const y0 = top + ((H - top - bot) - dy * leaves.length) / 2 + dy / 2;
    leaves.forEach((n, k) => { n.y = y0 + k * dy; });
    const setY = n => { if (n.ch.length) { n.ch.forEach(setY); n.y = (n.ch[0].y + n.ch[n.ch.length - 1].y) / 2; } };
    roots.forEach(setY);
    const blankAt = n => o.blank != null && n.d >= o.blank, hw = n => (blankAt(n) ? 3.4 : Math.max(1.6, String(n.t).length * fs * 0.32 + 0.4));
    const dx = D ? Math.min(o.dx || 30, (W - 6.8 - 8) / D) : 0, xl = (W - (D * dx + 6.8 + 3)) / 2 + 3.4, X = d => xl + d * dx;   // 図のまん中にそろえる
    let s = '';
    const draw = n => {
      const x = X(n.d), y = n.y;
      s += blankAt(n) ? h.rich(x, y + fs * 0.36, '{{' + n.t + '}}', fs, 'middle') : h.tx(x, y + fs * 0.36, n.t, fs, 'middle');
      n.ch.forEach(c => { s += h.ln(x + hw(n) + 0.9, y, X(c.d) - hw(c) - 0.9, c.y, '#222', 0.28); draw(c); });
    };
    roots.forEach(draw);
    if (o.heads) o.heads.forEach((t, d) => { s += h.tx(X(d), 3.6, t, fs - 0.2, 'middle', ' class="pl"'); });
    if (o.mark) s += h.ans(leaves.filter(n => o.mark(n.path)).map(n => `<ellipse cx="${h.f2(X(n.d))}" cy="${h.f2(n.y)}" rx="${h.f2(hw(n) + 1.5)}" ry="${h.f2(Math.min(2.6, dy / 2 - 0.2))}" fill="none" stroke="#d62828" stroke-width="0.4"/>`).join(''));
    return s;
  });

