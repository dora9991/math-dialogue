  const D5 = ['[[2/3]](6x−9y)−[[3/4]](8x−4y)', '4x−6y−6x+3y', '−2x−3y'];                                           // 使ってみる（5）
  const D6 = ['((3x+y)+(x+5y))×4÷2', '(4x+6y)×2', '8x+12y'];                                                       // 使ってみる（6）台形の面積
