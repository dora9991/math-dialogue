    edges.filter(e => !e.hidden).forEach(e => { out += h.ln(X(S[e.i]), Y(S[e.i]), X(S[e.j]), Y(S[e.j]), '#222', 0.34, ' stroke-linecap="round"'); });
    curves.forEach(c => { out += `<polyline points="${c.pts.map(p => h.f2(X(p)) + ',' + h.f2(Y(p))).join(' ')}" fill="none" stroke="${c.hidden ? '#555' : '#222'}" stroke-width="${c.hidden ? 0.22 : 0.34}"${c.hidden ? dashA : ''}/>`; });
