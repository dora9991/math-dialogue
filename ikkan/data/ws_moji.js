/* 板書型ワークシート：中1 文字と式。書き方は data/ws_kukan.js の先頭を見る。
   検算：node tools/verify.cjs　／　見た目：node tools/check.cjs */
(function () {
  const { M, K, B, G, F, C2, RECT } = IK.b;

  IK.add('moji-suryo', {
    unit: 'moji', unitName: '文字と式', no: '', title: '文字を使った式（数量の表し方・式の値）',
    summary: '長方形や代金を、文字を使った式で表し、数を代入して式の値を求める。学習課題＋例題2問。',
    head: '文字と式',
    checks: [
      'near((5 + 3) * 2, 2 * (5 + 3)) && near(2 * (5 + 3), 16)',               // 例題2：周の長さ
      'near(5 * 3, 15)',                                                       // 例題2：面積
      'near(80 * 3 + 120 * 2, 480)'                                            // 例題1：a＝3、b＝2 のとき 480 円（式 80a+120b の確かめ）
    ]
  }, [
    M('数量を、文字を使った式で表そう'),

    // ---- 学習課題（数字もすべて印刷する） ----
    C2([
      K('学習課題', '縦が a cm、横が b cm の長方形がある。\n周の長さと面積を、a と b の式で表そう。', 2),
      B(9, '周の長さ … 縦と横の和の 2 倍\n　(a+b)×2＝2(a+b)（cm）\n面積 … 縦×横\n　a×b＝ab（cm^2）\n【気づき】a や b にどんな数が入っても、\n　同じ式で周の長さと面積が求められる')
    ], [
      F(11, RECT({ w: 5, h: 3, top: 'b cm', side: 'a cm' }))
    ], '3:2'),

    G(1),

    // ---- 例題1（数字を空欄にする） ----
    K('例題1', '1個 {{80}} 円のパンを a 個と、1本 {{120}} 円の牛乳を b 本買った。代金の合計を、\na と b を使った式で表そう。', 2),
    B(8, 'パンの代金 … 80×a＝80a（円）\n牛乳の代金 … 120×b＝120b（円）\n合計 … 80a+120b（円）\n（答）80a+120b（円）\n確かめ … a＝3、b＝2 のとき　80×3+120×2＝480（円）'),

    G(1),

    // ---- 例題2 ----
    C2([
      K('例題2', '学習課題の長方形で、a＝{{5}}、\nb＝{{3}} のとき、\n周の長さと面積を求めよう。', 3),
      B(8, 'a に 5、b に 3 を代入する\n周の長さ … 2(a+b)＝2×(5+3)＝16（cm）\n面積 … ab＝5×3＝15（cm^2）\n式の中の文字に数を代入して求めた値を、\n　「式の値」という')
    ], [
      F(11, RECT({ w: 5, h: 3, top: '{{3}}cm', side: '{{5}}cm' }))
    ], '3:2')
  ]);
})();
