  const solve = (e1, e2) => { const [a, b, c] = lin(e1), [d, e, f] = lin(e2), D = a * e - b * d; return Math.abs(D) < 1e-9 ? null : [(c * e - b * f) / D, (a * f - c * d) / D]; };
