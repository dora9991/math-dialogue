/* 空間図形（新しい形） 第9時：角柱と円柱の表面積を、展開図を使って求めよう。 kukan-09 と同じ内容の授業を、新しい形に組みかえた（見本 lesson_kukan_new_01.js）。
   ・ワークシートは A4 1枚（約12分）：問いは1つ（三角柱の、すべての面の面積の和。数値は全部印刷）。個人3分 → ペア3分 → ことば → 例題（円柱の表面積。数字は空欄）。考えようは、演習プリントの裏へ。
   ・演習プリントは表裏：表＝確かめる 2問・使ってみる 4問（ここまでできたら今日の合格）／裏＝ひろげる 1問（考えよう：高さだけを2倍にすると、表面積は2倍になるか。答えは載せない）・チャレンジ★★ 1問（穴のあいた立方体の表面積。ヒントカードつき）。 2:4:1:1 の8問。
   ・図：三角柱・台形柱・穴のあいた立方体の見取図（ななめ投影。obl）、三角柱・円柱の展開図（netTri・netCyl）は、このファイルの中で描く。
   ・小テストは kukan-09 と同じ。
   検算：node tools/verify.cjs kukan_new-09　／　見た目：node tools/check.cjs <出力先> kukan_new-09 */
