/* 板書型ワークシート：中1 データの活用。書き方は data/ws_kukan.js の先頭を見る。
   検算：node tools/verify.cjs　／　見た目：node tools/check.cjs */
(function () {
  const { M, K, B, G, F, C2, HIST } = IK.b;
  // 50m 走の記録（30 人）と、テストの得点（20 人）。図の棒と、板書の数字は、ここから外れてはいけない（checks で確かめる）
  const RUN = [3, 9, 11, 5, 2], TEST = [1, 3, 6, 7, 3];

  IK.add('data-histogram', {
    unit: 'data', unitName: 'データの活用', no: '', title: 'ヒストグラムの読み取り（階級・度数・相対度数）',
    summary: 'ヒストグラムから、階級の幅・最頻値・度数・相対度数を読み取る。学習課題＋例題2問。',
    head: 'データの活用',
    checks: [
      `near(${JSON.stringify(RUN)}.reduce((a, b) => a + b), 30) && near(3 + 9 + 11 + 5 + 2, 30)`,                  // 学習課題：度数の合計 30 人（板書の足し算とも合う）
      `near(Math.max(...${JSON.stringify(RUN)}), 11) && ${JSON.stringify(RUN)}.indexOf(11) === 2 && near((8.0 + 9.0) / 2, 8.5)`,   // いちばん多いのは 8.0〜9.0 秒（図の 3 番目）、階級値 8.5
      `near(${JSON.stringify(TEST)}.reduce((a, b) => a + b), 20)`,                                                // 例題：度数の合計 20 人
      `near(${JSON.stringify(TEST)}[3], 7) && near(7 / 20, 0.35)`,                                                // 例題1：30 点以上 40 点未満
      `near(${JSON.stringify(TEST)}[2] + ${JSON.stringify(TEST)}[3], 13) && near(13 / 20, 0.65)`                  // 例題2：20 点以上 40 点未満
    ]
  }, [
    M('ヒストグラムから、データの特徴を読み取ろう'),

    // ---- 学習課題（数字もすべて印刷する） ----
    C2([
      K('学習課題', '右のヒストグラムは、30 人の\n50\\m 走の記録である。\n階級の幅と、人数がいちばん多い\n階級を調べよう。', 4),
      B(9, '階級の幅 … 1 秒\n度数がいちばん多い階級 …\n　8.0 秒以上 9.0 秒未満（11 人）\n最頻値 … その階級の階級値\n　　　[[8.0+9.0/2]]＝8.5（秒）\n度数の合計 … 3+9+11+5+2＝30（人）')
    ], [
      F(13, HIST({ edges: [6, 7, 8, 9, 10, 11], counts: RUN, ymax: 12, ystep: 1, xname: '(秒)', yname: '(人)', hl: [2] }))
    ], '11:9'),

    G(1),

    // ---- 例題1・例題2（数字を空欄にする。ヒストグラムは 2 問で共通） ----
    C2([
      K('例題1', '右のヒストグラムは、20 人の\nテストの得点である。\n{{30}}点以上{{40}}点未満の階級の、\n度数と相対度数を求めよう。', 4),
      B(6, '度数 … 7 人\n相対度数 … 度数÷度数の合計\n　　　　　7÷20＝0.35\n（答）度数 7 人、相対度数 0.35'),
      G(1),
      K('例題2', '{{20}}点以上{{40}}点未満の人は、\n何人で、全体の何 % か。', 2),
      B(7, '20 点以上 30 点未満 … 6 人\n30 点以上 40 点未満 … 7 人\n6+7＝13（人）\n13÷20＝0.65　→　65 %\n（答）13 人、65 %')
    ], [
      F(13, HIST({ edges: [0, 10, 20, 30, 40, 50], counts: TEST, ymax: 8, ystep: 1, xname: '(点)', yname: '(人)' }))
    ], '11:9')
  ]);
})();
