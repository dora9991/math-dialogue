    let out = h.tx(W / 2, 3.6, '展開図（ここにかこう）', 3, 'middle', ' class="cap"') + `<rect x="1.5" y="${cap}" width="${f2(W - 3)}" height="${f2(H - cap - 1.5)}" rx="2" fill="none" stroke="#8b96a3" stroke-width="0.3" stroke-dasharray="1.2 0.9"/>`;
