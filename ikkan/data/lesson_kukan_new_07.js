    a += h.tx(cx, top + d + rh / 2 + 1, '横 2π×3＝6π cm', 2.9, 'middle') + h.tx(x0 + rw + 2, top + d + rh / 2 + 1, '縦', 2.9, 'start') + h.tx(x0 + rw + 2, top + d + rh / 2 + 5, '10cm', 2.9, 'start');
