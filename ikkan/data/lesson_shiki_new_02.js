  const D2 = [['(3a+2b)+(a−5b)', '3a+2b+a−5b', '4a−3b'], ['(5a+3b)−(2a+b)', '5a+3b−2a−b', '3a+2b']];           // 確かめる（2）加法・減法
  const D3 = [['(x−4y)+(−3x+2y)', 'x−4y−3x+2y', '−2x−2y'], ['(x−2y)−(4x−5y)', 'x−2y−4x+5y', '−3x+3y']];        // 使ってみる（3）
  const D4 = ['(5x+2y−1)−(3x−4y+2)', '5x+2y−1−3x+4y−2', '2x+6y−3'];                                              // 使ってみる（4）数の項がある
  const D5 = ['([[1/2]]a−[[1/3]]b)+([[1/6]]a+[[2/3]]b)', '[[1/2]]a−[[1/3]]b+[[1/6]]a+[[2/3]]b', '[[2/3]]a+[[1/3]]b'];   // 使ってみる（5）係数が分数
  const D6 = ['(3a+2b)+(a−b)+(2a+4b)', '3a+2b+a−b+2a+4b', '6a+5b'];                                              // 使ってみる（6）周の長さ
