  const JS = src => {
    const P = str => {
      const s = str.replace(/[\s{}]/g, '').replace(/−/g, '-');
      let i = 0;
      const num = () => { let t = ''; while (i < s.length && /[0-9.]/.test(s[i])) t += s[i++]; return t; };
      const atom = () => {
        if (s.startsWith('[[', i)) { const e = s.indexOf(']]', i), b = s.slice(i + 2, e), k = b.indexOf('/'); i = e + 2; return `(${P(b.slice(0, k))}/${P(b.slice(k + 1))})`; }
        if (s[i] === '(') { i++; const t = expr(); i++; return `(${t})`; }
        if (/[0-9]/.test(s[i])) return num();
        return s[i++];
      };
      const pow = () => { const a = atom(); if (s[i] !== '^') return a; i++; return `(${a}**${num()})`; };
      const juxt = () => { let t = pow(); while (i < s.length && /[0-9A-Za-z(\[]/.test(s[i])) t = `(${t}*${pow()})`; return t; };
      const prod = () => { let t = juxt(); while (s[i] === '×' || s[i] === '÷') { const o = s[i++] === '×' ? '*' : '/'; t = `(${t}${o}${juxt()})`; } return t; };
      const term = () => { let neg = false; if (s[i] === '-') { neg = true; i++; } else if (s[i] === '+') i++; const t = prod(); return neg ? `(-${t})` : t; };
      const expr = () => { let t = term(); while (s[i] === '+' || s[i] === '-') { const o = s[i++]; t = `(${t}${o}${term()})`; } return t; };
      const r = expr();
      if (i !== s.length) throw new Error('式を読めない：' + str);
      return r;
    };
    return P(src);
  };
  const ex = (f, g) => {
    const vs = [...new Set((f + g).replace(/[^a-z]/g, ''))];
    return vs.reduceRight((inner, v) => `[-3, -2, -1, 1, 2, 3].every(${v} => ${inner})`, `near(${JS(f)}, ${JS(g)})`);
  };
  const chain = list => list.slice(1).map(u => ex(list[0], u)).join(' && ');          // 列のすべての式が、最初の式と等しい
  const chains = lists => lists.map(chain).join(' && ');
