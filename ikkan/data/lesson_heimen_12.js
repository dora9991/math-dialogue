    k.shade = d => { k.s += `<path d="${d}" fill="${GRAY}" fill-rule="evenodd" stroke="${INK}" stroke-width="0.32" stroke-linejoin="round"/>`; return k; };   // d の中を、うすい色でぬる（evenodd：重なったところは、ぬかない）
