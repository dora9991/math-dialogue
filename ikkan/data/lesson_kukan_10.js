    edges.filter(e => !e.hidden).forEach(e => { out += h.ln(X(S[e.i]), Y(S[e.i]), X(S[e.j]), Y(S[e.j]), '#222', 0.34, ' stroke-linecap="round"'); });
    segs.forEach(s => { out += h.ln(X(s.a), Y(s.a), X(s.b), Y(s.b), '#222', 0.22, s.dash ? dashA : ''); });
