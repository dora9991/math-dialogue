    out += `<ellipse cx="${f2(cx)}" cy="${f2(cy - R)}" rx="${f2(R)}" ry="${f2(ry)}" fill="none" stroke="#222" stroke-width="0.32"/>`;
    out += back(cx, cy + R, R, ry) + front(cx, cy + R, R, ry);
    out += `<circle cx="${f2(cx)}" cy="${f2(cy)}" r="${f2(R)}" fill="#eef3fa" fill-opacity="0.7" stroke="#222" stroke-width="0.32"/>`;
