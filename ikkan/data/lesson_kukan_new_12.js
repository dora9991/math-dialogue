    const R = 11, q = 0.28, ry = q * R, yT = 11, yB = yT + 2 * R, xs = [W * 0.2, W * 0.5, W * 0.8];
    let out = '';
    // ア 円柱
    out += h.ln(xs[0] - R, yT, xs[0] - R, yB, '#222', 0.32) + h.ln(xs[0] + R, yT, xs[0] + R, yB, '#222', 0.32);
    out += `<ellipse cx="${f2(xs[0])}" cy="${yT}" rx="${R}" ry="${f2(ry)}" fill="none" stroke="#222" stroke-width="0.32"/>` + back(xs[0], yB, R, ry) + front(xs[0], yB, R, ry);
    // イ 円錐（頂点から底面のだ円にひいた接線）
