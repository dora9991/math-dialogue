      // （8）15個：3 7 13 19 27（前半 3 4 6 7 9 10 12 の中央値 7、中央値 13、後半 15 16 18 19 21 24 27 の中央値 19）。ア（3 9 13 21 27）・ウ（3 7 10 19 27）とは、ちがう
