  const C12 = [10, 13, 15, 19, 21, 24, 26, 28, 31, 35, 37, 44];                  // （7）考えよう（12人）
  const N15 = [3, 4, 6, 7, 9, 10, 12, 13, 15, 16, 18, 19, 21, 24, 27];           // （8）15個

