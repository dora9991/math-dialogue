/* 板書型ワークシート：中1 比例と反比例。書き方は data/ws_kukan.js の先頭を見る。
   検算：node tools/verify.cjs　／　見た目：node tools/check.cjs */
(function () {
  const { M, K, B, G, F, C2, CO } = IK.b;
  const X5 = [-2, -1, 0, 1, 2];
  // 座標平面（x：−3〜3、y：−6〜6）。線と点は、解答を表示したときだけ赤で出る
  const plane = (a, from, to, text, at, anchor) => CO({ xmin: -3, xmax: 3, ymin: -6, ymax: 6, lines: [{ a, from, to, text, at, anchor }], points: X5.map(x => ({ x, y: a * x })) });

  IK.add('hirei-graph', {
    unit: 'hirei', unitName: '比例と反比例', no: '', title: '比例のグラフ',
    summary: '表をつくり、点をとって、比例 y＝ax のグラフをかく。学習課題＋例題2問。',
    head: '比例と反比例',
    checks: [
      'near(2 * -2, -4) && near(2 * -1, -2) && near(2 * 1, 2) && near(2 * 2, 4)',     // 学習課題 y＝2x
      'near(3 * -2, -6) && near(3 * -1, -3) && near(3 * 1, 3) && near(3 * 2, 6)',     // 例題1 y＝3x
      'near(-2 * -2, 4) && near(-2 * -1, 2) && near(-2 * 1, -2) && near(-2 * 2, -4)', // 例題2 y＝−2x
      'near(2 * 2 - 2 * 1, 2) && near(3 * 2 - 3 * 1, 3) && near(-2 * 2 - (-2 * 1), -2)'   // x が 1 増えたときの y の変わり方＝比例定数
    ]
  }, [
    M('比例 y＝ax のグラフのかき方を考えよう'),

    // ---- 学習課題（数字もすべて印刷する） ----
    C2([
      K('学習課題', '比例 y＝2x のグラフをかこう。\nx の値が −2、−1、0、1、2 のとき、\ny の値を求めて、点を結ぼう。', 3),
      B(8, 'x … −2、−1、0、1、2\ny … −4、−2、0、2、4\n点 (−2, −4)、(−1, −2)、(0, 0)、\n　　(1, 2)、(2, 4) をとる\n点を直線で結ぶ　→　原点を通る直線\nx が 1 増えると、y は 2 増える')
    ], [
      F(11, plane(2, -3, 3, 'y＝2x', [3.2, 5.7], 'start'))
    ], '3:2'),

    G(1),

    // ---- 例題1（数字を空欄にする） ----
    C2([
      K('例題1', '比例 y＝{{3}}x のグラフをかこう。\nx の値が −2、−1、0、1、2 のとき、\ny の値を求めよう。', 3),
      B(8, 'x … −2、−1、0、1、2\ny … −6、−3、0、3、6\n原点と点 (1, 3) を通る直線\nx が 1 増えると、y は 3 増える\ny＝3x のほうが y＝2x より、かたむきが急')
    ], [
      F(11, plane(3, -2, 2, 'y＝3x', [2.2, 5.7], 'start'))
    ], '3:2'),

    G(1),

    // ---- 例題2 ----
    C2([
      K('例題2', '比例 y＝−{{2}}x のグラフをかこう。\nまた、x の値が 1 増えるとき、\ny はどう変わるかを答えよう。', 3),
      B(8, 'x … −2、−1、0、1、2\ny … 4、2、0、−2、−4\n原点と点 (1, −2) を通る直線（右下がり）\n（答）x が 1 増えると、y は 2 減る\n比例定数が負 → 右下がりのグラフ')
    ], [
      F(11, plane(-2, -3, 3, 'y＝−2x', [-3.2, 5.7], 'end'))
    ], '3:2')
  ]);
})();
