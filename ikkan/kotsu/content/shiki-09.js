//   テンプレート id＝「09」＋ d（演習）／q（小テスト）＋ ikkan の問題の番号（＋ 小問ごとに a, b…）。例：09d03a ＝ shiki-09.dr.3 の1つ目
//   式を答える問題は入力欄で打てないので、(a) 式の中の数（定数項・倍数）を聞く／(b) 4択（誤答は、符号まちがい・向きのとりちがいなど）にした。
//   「説明しよう」は、説明の中の1つの式（和・変形）か、読み取り（偶数・奇数・3の倍数）を聞く形に直した。
//   カレンダーは、図のかわりに「ある数の真下は 7 大きい、右どなりは 1 大きい」という約束（ふつうのカレンダー）で、位置を言葉で言い切る。
//   式は algebra.js の多項式で作る（手で書かない）。
