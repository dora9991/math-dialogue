//   ikkan の演習プリント（kukan-02.dr.1〜11）・小テスト（kukan-02.qz.1〜5）を、コツコツくんのテンプレートにしたもの。
//   テンプレート id＝「02」＋ d（演習）／q（小テスト）＋ ikkan の問題の番号。例：02d04 ＝ kukan-02.dr.4、02q03 ＝ kukan-02.qz.3
//   5つの正多面体の事実（面の数・面の形・1つの頂点に集まる面の数）は、下の表 FACTS に持つ。
//   辺の数・頂点の数は、表から計算する：辺＝面の形の辺の数×面の数÷2、頂点＝面の形の辺の数×面の数÷1つの頂点に集まる面の数（手で書かない）。
// ============================================================
import { t, pick, choices4, shuffle, sample } from "../kit.js";
import { unit } from "../kukan-kit.js";
import { hedronName, NGON } from "../solids.js";

const SHAPE = { 3: "正三角形", 4: "正方形", 5: "正五角形", 6: "正六角形" };
const SHAPE_ALL = [3, 4, 5, 6].map((n) => SHAPE[n]);
const WORD = { F: "面の数", E: "辺の数", V: "頂点の数" };
const UNIT = { F: "つ", E: "本", V: "個" };

// ── 5つの正多面体の事実（表）：F＝面の数、n＝面の形の辺の数（3＝正三角形、4＝正方形、5＝正五角形）、k＝1つの頂点に集まる面の数 ──
const FACTS = [
  { F: 4, n: 3, k: 3 },    // 正四面体
  { F: 6, n: 4, k: 3 },    // 正六面体（立方体）
  { F: 8, n: 3, k: 4 },    // 正八面体
  { F: 12, n: 5, k: 3 },   // 正十二面体
  { F: 20, n: 3, k: 5 },   // 正二十面体
];
/** 表から計算して、辺の数 E・頂点の数 V をつける */
const REG = FACTS.map((p) => ({ ...p, name: "正" + hedronName(p.F), E: (p.F * p.n) / 2, V: (p.F * p.n) / p.k }));
// 表の検算：辺・頂点が整数になり、頂点−辺+面＝2 が成り立つ
REG.forEach((p) => {
  if (!Number.isInteger(p.E) || !Number.isInteger(p.V) || p.V - p.E + p.F !== 2) throw new Error(`正多面体の表が合わない: ${p.name}`);
});
const [TETRA, HEXA, OCTA, DODECA, ICOSA] = REG;

/** ほかの正多面体の名前（正解をのぞく）をシャッフルして、先に trap を置く */
const otherNames = (r, ans, trap = []) => [...trap.map((x) => x.name), ...shuffle(r, REG.map((x) => x.name))].filter((x) => x !== ans);

/** 辺・頂点を求める式（steps 用） */
const calcLine = (p, w) =>
  w === "E" ? `辺 … ${p.n}×${p.F}÷2＝${p.E}（本）` : `頂点 … ${p.n}×${p.F}÷${p.k}＝${p.V}（個）`;

// 正多面体でないものの例（理由つき）
const NON_REG = [
  ["直方体", "面が長方形で、正多角形ではない（面の形・大きさもそろっていない）。"],
  ["底面が正方形で、側面がすべて正三角形の四角錐", "底面は正方形、側面は正三角形で、面の形がそろっていない。"],
  ["底面が正三角形で、側面がすべて長方形の三角柱", "底面は正三角形、側面は長方形で、面の形がそろっていない。"],
  ["底面が正五角形で、側面がすべて長方形の五角柱", "底面は正五角形、側面は長方形で、面の形がそろっていない。"],
  ["2つの合同な正四面体を、1つの面ではり合わせた立体", "頂点に集まる面の数が、3つの頂点と 4つの頂点があって、そろっていない。"],
];
const REG_NAMES = ["正四面体", "立方体", "正八面体", "正十二面体", "正二十面体"];

// 切り落としの数（もとが p のとき）：面＝F+V、頂点＝V×k、辺＝E+V×k
const cutFEV = (p) => ({ F: p.F + p.V, V: p.V * p.k, E: p.E + p.V * p.k });
const cutQ = (p, w) =>
  `${p.name}の ${p.V}個の頂点を、それぞれ、その頂点に集まる辺を 3等分する点（頂点に近いほうの点）を通る平面で、すべて切り落とした。できた立体の、${WORD[w]}は？（切り口は、となり合う切り口と重ならない）`;
const cutSteps = (p) => {
  const c = cutFEV(p);
  return [
    `面 … もとの面 ${p.F} + 切り口 ${p.V} = ${c.F}`,
    `頂点 … 切り口の${NGON[p.k]}の頂点 ${p.k}×${p.V} = ${c.V}`,
    `辺 … もとの辺 ${p.E} + 切り口の辺 ${p.k}×${p.V} = ${c.E}`,
    `確かめ　${c.V} − ${c.E} + ${c.F} = ${c.V - c.E + c.F}`,
  ];
};
const cutTpl = (id, pool) =>
  t(id, (r) => {
    const p = pick(r, pool), w = pick(r, ["F", "E", "V"]), c = cutFEV(p);
    return {
      q: cutQ(p, w),
      ans: c[w],
      unit: UNIT[w],
      hint: `もとの面・辺と、切り口でふえた面・辺に分けて数えよう。切り口の形は、頂点に集まる辺の数と同じ角形になる。`,
      steps: cutSteps(p),
    };
  });

