/** t(id, build) と同じ。ただし、数の答えが問題文の数とたまたま同じになる組は、作り直す（skip） */
const t = (id, build) => t0(id, (r) => {
  const p = build(r);
  return p && typeof p.ans === "number" && ((p.q.match(/\d+/g) || []).map(Number)).includes(p.ans) ? { skip: true } : p;
});

// ── 道具（この授業の問題用に足した小さな関数）──────────────────────────
const $ = (s) => `$${s}$`;
const KD = ["", "一", "二", "三", "四", "五", "六", "七", "八", "九"];
const kanji = (n) => (n < 10 ? KD[n] : n < 20 ? "十" + KD[n - 10] : KD[Math.floor(n / 10)] + "十" + KD[n % 10]);
const gon = (n) => `${kanji(n)}角形`;      // 六角形
const rgon = (n) => `正${kanji(n)}角形`;   // 正六角形
const NM = "ABCDEFGHIJKL";
const names = (n) => NM.slice(0, n);       // "ABCDE"
const total = (n) => 180 * (n - 2);        // n角形の内角の和
const m5 = (r, lo, hi) => 5 * r(lo / 5, hi / 5);

/** n角形の内角のうち、1つ（頂点 ask）を求める問題。ほかの内角（5の倍数）は問題文で言う。sum が total(n) になる */
function polyAngles(r, n, { lo = 60, hi = 150, xlo = 45, xhi = 165, right = false } = {}) {
  for (let i = 0; i < 500; i++) {
    const a = Array.from({ length: n }, () => m5(r, lo, hi)), ask = r(0, n - 1);
    if (right) a[(ask + r(1, n - 1)) % n] = 90;      // 直角を 1つ、問われていない頂点に入れる
    const rest = a.reduce((s, v, k) => (k === ask ? s : s + v), 0), x = total(n) - rest;
    if (x < xlo || x > xhi || x % 5) continue;
    a[ask] = x;
    return { a, ask };
  }
  return null;
}
function polyQ(r, n, opt) {
  const g = polyAngles(r, n, opt);
  if (!g) return { skip: true };
  const { a, ask } = g, tot = total(n), V = NM[ask];
  const given = a.map((v, k) => (k === ask ? null : `∠${NM[k]}＝${v}°`)).filter(Boolean);
  const nums = a.filter((v, k) => k !== ask).map((v) => `${v}°`).join("+");
  return {
    q: `${gon(n)} ${names(n)} で、${given.join("、")} のとき、∠${V} の大きさは？`,
    ans: a[ask],
    unit: "度",
    hint: "$n$ 角形の内角の和を求める式を、思い出そう。内角の和から、わかっている角をひくと、どうなるかな？",
    steps: [`${gon(n)}の内角の和は　180°×(${n}−2)＝${tot}°`, `∠${V}＝${tot}°−(${nums})＝${a[ask]}°`],
  };
}

/** 正n角形の1つの内角（n は 360 の約数） */
function oneInterior(r, pool) {
  const n = pick(r, pool), tot = total(n), a = tot / n;
  return {
    q: pick(r, [`${rgon(n)}の 1つの内角の大きさは？`, `${rgon(n)}は、${n}個の内角がすべて等しい。1つの内角の大きさは？`]),
    ans: a,
    unit: "度",
    hint: "正多角形の内角の和は、どう求められたかな？ 正多角形の内角は、すべてどうなっているかな？",
    steps: [`${rgon(n)}の内角の和は　180°×(${n}−2)＝${tot}°`, `内角は ${n}個とも等しいので、1つの内角は　${tot}°÷${n}＝${a}°`],
  };
}
/** n角形の内角の和 */
function sumQ(r, lo, hi) {
  const n = r(lo, hi), tot = total(n);
  return {
    q: pick(r, [`${gon(n)}の内角の和は何度か。`, `${gon(n)}の ${n}個の内角の大きさを、すべてたすと、何度になるか。`]),
    ans: tot,
    unit: "度",
    hint: `${gon(n)}は、1つの頂点から対角線をひくと、何個の三角形に分けられるかな？`,
    steps: [`${gon(n)}は、1つの頂点から対角線をひくと、三角形が ${n}−2＝${n - 2}個できる。`, `内角の和は　180°×${n - 2}＝${tot}°`],
  };
}
/** 内角の和から、何角形か */
function nFromSum(r, lo, hi) {
  const n = r(lo, hi), tot = total(n);
  return {
    q: pick(r, [`内角の和が ${tot}° になる多角形は、何角形か。`, `ある多角形の内角の和は ${tot}° である。この多角形は、何角形か。`]),
    ans: n,
    unit: "角形",
    hint: "$n$ 角形の内角の和を表す式に、わかっている内角の和をあてはめると、どんな方程式ができるかな？",
    steps: [`${$("n")} 角形の内角の和は ${$("180^\\circ\\times(n-2)")} と表される。`, `これが ${tot}° にあたるので　${$(`n-2=${tot}\\div 180=${tot / 180}`)}`, `${$(`n=${n}`)} だから、${gon(n)}。`],
  };
}
/** 1つの内角が a° の正多角形は、正何角形か（方程式 180(n−2)＝an） */
const nFromInterior = (r, pool) => {
  const a = pick(r, pool), n = 360 / (180 - a);
  return { a, n };
};
const eqSteps = (a, n) => [
  `内角の和を、2通りに表す。公式から　${$("180(n-2)")} 度。1つの内角 ${a}° が ${$("n")} 個で　${$(`${a}n`)} 度。`,
  `この 2つが等しいから　${$(`180n-360=${a}n`)}`,
  `${$(`${180 - a}n=360`)}　より　${$(`n=${n}`)}`,
  `よって、${rgon(n)}。`,
];

