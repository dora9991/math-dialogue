/** 「n回のうち k回」から確率を求める問題の本体。ctxs＝使う場面（TRY の一部）、maxD＝割合の小数の位の上限 */
const probFromCounts = (r, ctxs, maxD = 2) => {
  const C = pick(r, ctxs), n = pick(r, C.n), d = Math.min(C.d, maxD);
  const k = pickK(r, n, C.lo, C.hi, d);
  if (k == null) return { skip: true };
  const p = round(k / n);
  return {
    q: `${C.f(n, k)}${C.ev}を、小数で求めよう。`,
    ans: p,
    hint: "確率は、（起こった回数）÷（全体の回数）で求める。何回のうち何回かな？",
    steps: ["確率 ＝ 起こった回数 ÷ 全体の回数", `${k}÷${n} ＝ ${p}`, `${C.ev}は ${p}。`],
  };
};

