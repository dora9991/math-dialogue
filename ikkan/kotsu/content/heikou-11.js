// ── 連続する整数などの和 ───────────────────────────────────────────
//   kind：int＝連続する整数（真ん中 n）、even＝連続する偶数（真ん中 2n）、odd＝連続する奇数（真ん中 2n+1）、m3＝連続する3の倍数（真ん中 3n）、m4＝連続する4の倍数（真ん中 4n）
const CONS = {
  int: { word: "整数", a: 1, c0: 0, step: 1, mid: "n", gcd: (k) => k },
  even: { word: "偶数", a: 2, c0: 0, step: 2, mid: "2n", gcd: (k) => 2 * k },
  odd: { word: "奇数", a: 2, c0: 1, step: 2, mid: "2n+1", gcd: (k) => k },
  m3: { word: "3の倍数", a: 3, c0: 0, step: 3, mid: "3n", gcd: (k) => 3 * k },
  m4: { word: "4の倍数", a: 4, c0: 0, step: 4, mid: "4n", gcd: (k) => 4 * k },
};
const termStr = (a, c) => `${a === 1 ? "" : a}n${c === 0 ? "" : c > 0 ? `+${c}` : `−${-c}`}`;
/** k 個の連続する数（種類 kind）：項（n の式の文字列）と、和の係数 [a, c]（和＝a n + c） */
function consTerms(kind, k) {
  const C = CONS[kind], h = (k - 1) / 2, terms = [];
  for (let i = -h; i <= h; i++) terms.push(termStr(C.a, C.c0 + C.step * i));
  return { terms, sum: [C.a * k, C.c0 * k] };
}
const sumTex = ([a, c]) => poly([a, c], "n");
const paren = (s) => (/[+−]/.test(s) ? `(${s})` : s);
/** 和の式の4択 */
function consExprQ(r, kinds, ks) {
  const kind = pick(r, kinds), k = pick(r, ks), C = CONS[kind], { terms, sum } = consTerms(kind, k);
  const ans = $(sumTex(sum));
  const wr = [[sum[0], sum[1] + 1], [sum[0], sum[1] - 1], [sum[0] - 1, sum[1]], [sum[0] + 1, sum[1]], [sum[0] * 2, sum[1]], [sum[0], sum[1] + C.step], [k, 0], [sum[0], 0]]
    .filter(([a, c]) => !(a === sum[0] && c === sum[1]) && a > 0).map(([a, c]) => $(sumTex([a, c])));
  const uniq = [...new Set(wr)];
  return {
    q: `連続する${k}つの${C.word}の真ん中を $${C.mid}$（$n$ は整数）とする。${k}つの${C.word}の和を、$n$ の式で表すと、次のうちどれか。`,
    ans,
    choices: choices4(r, ans, shuffle(r, uniq).slice(0, 3)),
    hint: `${k}つの${C.word}を、真ん中の ${C.mid} を使って、1つずつ式で表してみよう。たしたら、どうなるかな？`,
    steps: [`${k}つの${C.word}は　${terms.join("、")}`, `その和は　${terms.map(paren).join("+")}＝${sumTex(sum)}`, `答えは ${ans}。`],
  };
}

