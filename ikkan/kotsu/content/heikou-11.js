/** 等式の性質：a＝b ならば、a+c＝b+c（式は $ で囲む） */
function stmtAlg(r, A) {
  const L = shuffle(r, A ? ["p", "q", "s", "t", "u"] : ["a", "b", "c", "d", "e"]), [p, q, m] = L, op = pick(r, ["+", "-", "\\times"]);
  const e = (v) => (op === "\\times" ? `${v}${m}` : `${v}${op}${m}`);
  return mk($(`${p}=${q}`), $(`${e(p)}=${e(q)}`));
}
