  do { x = 5 * r(4, 17); y = 5 * r(4, 17); } while (x + y > 150 || x === y);
  const z = 180 - x - y, T = `△${a}${b}${c}`;
  return { ...mk(`${T} で、∠${V[0]}＝${x}°、∠${V[1]}＝${y}°`, `∠${V[2]}＝${z}°`), x, y, z, V, T };
