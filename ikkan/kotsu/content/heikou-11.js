const termStr = (a, c) => `${a === 1 ? "" : a}n${c === 0 ? "" : c > 0 ? `+${c}` : `-${-c}`}`;   // TeX（$ の中に入れる）
/** k 個の連続する数（種類 kind）：項（n の式の文字列）と、和の係数 [a, c]（和＝a n + c） */
function consTerms(kind, k) {
  const C = CONS[kind], h = (k - 1) / 2, terms = [];
  for (let i = -h; i <= h; i++) terms.push(termStr(C.a, C.c0 + C.step * i));
  return { terms, sum: [C.a * k, C.c0 * k] };
}
const sumTex = ([a, c]) => poly([a, c], "n");
const paren = (s) => (/[+-]/.test(s) ? `(${s})` : s);
/** 連続する k 個の（種類 kind の）数の和についてのことがら */
function consStmt(r, kind, k) {
  const C = CONS[kind], g = C.gcd(k);
  return mk(`${k}つの${C.word}が連続している`, `その和は ${g} の倍数`, { kind, k });
}
/** consStmt の組（同じ種類で、k がちがう）用 */
const consGen = (kinds, ks) => (r, A) => { const kind = A ? A.kind : pick(r, kinds); return consStmt(r, kind, pick(r, ks.filter((kk) => !A || kk !== A.k))); };

/** 和の式の4択。誤答は、よくある誤り（定数項だけちがう・係数だけちがう・係数も定数項もちがう）を広くあつめて、正解と、長さ・似かたが目立たないものをえらぶ */
function consExprQ(r, kinds, ks) {
  const kind = pick(r, kinds), k = pick(r, ks), C = CONS[kind], { terms, sum } = consTerms(kind, k);
  const ans = $(sumTex(sum));
  const [A0, C0] = sum, S1 = C.step;
  const combos = [];
  for (const dA of [0, -C.a, C.a, 2 * C.a, -2 * C.a, 1, -1, A0]) for (const dC of [0, S1, -S1, 1, -1, 2 * S1, k, -k]) {
    const x = A0 + dA, y = C0 + dC;
    if (x <= 0 || (x === A0 && y === C0)) continue;
    // 正解と同じ形（定数項がないなら、「kn」の形だけ。定数項があるなら、定数項のある形だけ）にする。形で、正解を当てられないように
    if ((C0 === 0) !== (y === 0)) continue;
    if (C0 === 0 && x === A0) continue;
    combos.push([x, y]);
  }
  const pool = [...new Set(combos.map(([x, y]) => $(sumTex([x, y]))))].filter((x) => x !== ans);
  const KJ = { 3: "三", 5: "五", 7: "七" };   // 問題文の「つの数」は漢数字にして、正解の係数が、問題文にある数字と同じで目立たないように
  const q = `連続する${KJ[k]}つの${C.word}の真ん中を $${C.mid}$（$n$ は整数）とする。${KJ[k]}つの${C.word}の和を、$n$ の式で表すと、次のうちどれか。`;
  return {
    q,
    ans,
    choices: choices4(r, ans, pickWrongs(r, ans, pool, 3, q)),
    hint: `${k}つの${C.word}を、真ん中の $${C.mid}$ を使って、1つずつ式で表してみよう。たしたら、どうなるかな？`,
    steps: [`${k}つの${C.word}は　${terms.map($).join("、")}`, `その和は　${$(`${terms.map(paren).join("+")}=${sumTex(sum)}`)}`, `答えは ${ans}。`],
  };
}

