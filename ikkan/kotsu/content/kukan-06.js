const NOTE = "（柱や錐は、底面を下にして置いている）";

/** 角柱の平面図（底面の形）の言い方。四角柱は長方形、ほかは正n角形 */
const planPrism = (n) => (n === 4 ? "長方形" : `正${NGON[n]}`);
/** 角錐の平面図の言い方（底面の形に、頂点から出る辺が見える） */
const planPyr = (n) => (n === 4 ? "正方形に、2本の対角線が入った図" : `正${NGON[n]}の中心から、すべての頂点へ線がのびた図`);
const nb = (n, lo, hi) => (n + 1 <= hi ? n + 1 : n - 1 >= lo ? n - 1 : n + 2);   // n のとなりの数（lo〜hi の中で）

/** 立体（底面を下にして置く）の、立面図・平面図の言い方と、名前・ありがちな誤答 */
function solidInfo(r, k, n) {
  if (k === "prism") return { name: prismName(n), up: "長方形", dn: planPrism(n), wrongs: [pyramidName(n), prismName(nb(n, 3, 8)), "円柱"], why: `立面図が長方形なので、柱。平面図が${planPrism(n)}なので、底面は${NGON[n]}。` };
  if (k === "pyr") return { name: pyramidName(n), up: "二等辺三角形", dn: planPyr(n), wrongs: [prismName(n), pyramidName(nb(n, 3, 8)), "円錐"], why: `立面図が三角形なので、錐。平面図の外側の形が${NGON[n]}なので、底面は${NGON[n]}。` };
  if (k === "cyl") return { name: "円柱", up: "長方形", dn: "円", wrongs: ["円錐", prismName(r(3, 6)), "球"], why: "立面図が長方形なので柱。平面図が円なので、底面は円。" };
  if (k === "cone") return { name: "円錐", up: "二等辺三角形", dn: "円と、その中心の点", wrongs: ["円柱", pyramidName(r(3, 6)), "球"], why: "立面図が三角形なので錐。平面図が円なので、底面は円。" };
  return { name: "球", up: "円", dn: "円", wrongs: ["円柱", "円錐", "半球"], why: "どちらから見ても円。" };
}

/** 06d01・06q01：立面図・平面図の言い方から、立体の名前を選ぶ */
function nameFromProj(r, kinds) {
  const [k, n] = pick(r, kinds);
  const S = solidInfo(r, k, n);
  return {
    q: `ある立体を投影図で表したら、立面図は${S.up}、平面図は${S.dn}になった。この立体の名前は？${k === "sphere" ? "" : NOTE}`,
    ans: S.name,
    choices: choices4(r, S.name, S.wrongs),
    hint: "立面図から「柱か錐か」、平面図から「底面の形」を読み取ろう。",
    steps: [S.why, `この立体は「${S.name}」。`],
  };
}

