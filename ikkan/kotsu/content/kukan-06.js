/** 円錐台の立面図（上の辺 u、下の辺 w、高さ h。u・w は偶数なので、円の半径は整数） */
function frustum(r) {
  const a = r(1, 3), b = a + r(1, 3);
  return { u: 2 * a, w: 2 * b, h: r(2, 5) };
}

