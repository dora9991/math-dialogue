/** 直角三角形の3辺（直角をはさむ2辺と斜辺）。すべて整数 */
const TRI = [[3, 4, 5], [5, 12, 13], [6, 8, 10], [9, 12, 15], [8, 15, 17]];
const TRI_SMALL = TRI.slice(0, 4);   // 面積（辺の2乗）が大きくなりすぎない組

/** 縦と横が同じ長さ（正方形）にならないように、a を b とちがう数にする */
const diff = (a, b) => (a === b ? a + 1 : a);

/** 直角三角形の3辺と、軸にする辺・底面の半径になる辺（どちらが軸かは乱数） */
function tri(r, list = TRI) {
  const [x, y, c] = pick(r, list);
  const [ax, rad] = shuffle(r, [x, y]);
  return { x, y, c, ax, rad, sides: `${x}cm、${y}cm、${c}cm` };
}

