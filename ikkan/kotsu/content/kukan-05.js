/** L字形の説明文（図のかわり）。下の長方形は 横 R1・縦 H1、上の長方形は 横 R2・縦 H2。左のはしをそろえてのせ、左のはしの辺が軸 ℓ の上にある */
function LSHAPE(R1, H1, R2, H2) {
  return `L字形がある。横 ${R1}cm・縦 ${H1}cm の長方形（下）の上に、横 ${R2}cm・縦 ${H2}cm の長方形（上）を、左のはしをそろえてのせた形で、左のはしの辺（長さ ${H1 + H2}cm）が直線 ℓ の上にある。`;
}

