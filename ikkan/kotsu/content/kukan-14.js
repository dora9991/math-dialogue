// ───────── 円錐から小さい円錐を切りとった形（たらい・バケツ） ─────────
/**
 * 上の底面の半径 R、下の底面の半径 rr、深さ h、切りとった円錐の高さ x。
 *   rr : R = a : (a+1) なので、x = a·h（整数）。もとの円錐の高さは x+h。
 *   体積 = (R²(x+h) − rr²x) / 3 が整数になるよう、s か h を 3 の倍数にしてある。
 */
function frustum(rn, ratios) {
  const a = pick(rn, ratios);
  const mode = rn(0, 1);
  const s = mode ? pick(rn, [3, 6, 9]) : rn(2, 10);
  const h = mode ? rn(6, 20) : pick(rn, [6, 9, 12, 15, 18]);
  const rr = a * s, R = (a + 1) * s, x = a * h;
  const big = R * R * (x + h), small = rr * rr * x;
  if ((big - small) % 3 !== 0 || big % 3 !== 0 || small % 3 !== 0) return null;
  return { R, rr, h, x, H: x + h, bigV: big / 3, smallV: small / 3, V: (big - small) / 3 };
}
const frustumText = (nm, f) =>
  `${nm}は、円錐から、頂点をふくむ小さい円錐を切りとった形である。上の底面の直径が ${2 * f.R}cm、下の底面の直径が ${2 * f.rr}cm、深さが ${f.h}cm で、切りとった円錐の高さは ${f.x}cm である。`;
