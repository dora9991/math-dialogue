import { t as t0, pick, choices4, shuffle } from "../kit.js";
import { unitFor } from "../unit-kit.js";

const unit = unitFor("heikou");

/** t(id, build) と同じ。ただし、数の答えが問題文の数とたまたま同じになる組は、作り直す（skip） */
const t = (id, build) => t0(id, (r) => {
  const p = build(r);
  return p && typeof p.ans === "number" && ((p.q.match(/\d+/g) || []).map(Number)).includes(p.ans) ? { skip: true } : p;
});

// ── 道具（この授業の問題用に足した小さな関数）──────────────────────────
const $ = (s) => `$${s}$`;
const KD = ["", "一", "二", "三", "四", "五", "六", "七", "八", "九"];
const kanji = (n) => (n < 10 ? KD[n] : n < 20 ? "十" + KD[n - 10] : KD[Math.floor(n / 10)] + "十" + KD[n % 10]);
const gon = (n) => `${kanji(n)}角形`;
const rgon = (n) => `正${kanji(n)}角形`;
const NM = "ABCDEFGHIJKL";
const names = (n) => NM.slice(0, n);
const m5 = (r, lo, hi) => 5 * r(lo / 5, hi / 5);

/** 正n角形の1つの外角（n は 360 の約数） */
function oneExterior(r, pool) {
  const n = pick(r, pool), e = 360 / n;
  return {
    q: pick(r, [`${rgon(n)}の 1つの外角の大きさは？`, `${rgon(n)}では、${n}個の外角がすべて等しい。1つの外角の大きさは？`]),
    ans: e,
    unit: "度",
    hint: "多角形の外角の和は、何度だったかな？ 正多角形の外角は、すべてどうなっているかな？",
    steps: [`多角形の外角の和は、何角形でも 360°。`, `${rgon(n)}は、${n}個の外角がすべて等しいので、1つの外角は　360°÷${n}＝${e}°`],
  };
}
/** 1つの外角が e° の正多角形は、正何角形か */
function nFromExt(r, pool) {
  const e = pick(r, pool), n = 360 / e;
  return {
    q: pick(r, [`1つの外角が ${e}° である正多角形は、正何角形か。`, `正多角形がある。その 1つの外角の大きさは ${e}° である。この正多角形は、正何角形か。`]),
    ans: n,
    unit: "角形",
    hint: "外角の和は何度だったかな？ 正多角形の外角は、いくつ集まって、その和になるかな？",
    steps: [`正多角形の外角は、すべて等しく、その和は 360°。`, `外角が ${e}° だから　360°÷${e}°＝${n}　より、${rgon(n)}。`],
  };
}
/** 1つの内角が a° の正多角形は、正何角形か */
function nFromInt(r, pool) {
  const n = pick(r, pool), a = 180 - 360 / n, e = 180 - a;
  return {
    q: pick(r, [`1つの内角が ${a}° である正多角形は、正何角形か。`, `正多角形がある。その 1つの内角の大きさは ${a}° である。この正多角形は、正何角形か。`]),
    ans: n,
    unit: "角形",
    hint: "同じ頂点で、内角と外角の和は何度だったかな？ 外角がわかれば、頂点の数はどう求められるかな？",
    steps: [`内角と外角の和は 180° だから、1つの外角は　180°−${a}°＝${e}°`, `外角の和は 360° だから　360°÷${e}°＝${n}　より、${rgon(n)}。`],
  };
}
/** n角形の、ある頂点の外角（ほかの頂点の外角から） */
function extRest(r, n, { lo = 40, hi = 130, xlo = 25, xhi = 150 } = {}) {
  for (let i = 0; i < 500; i++) {
    const e = Array.from({ length: n }, () => m5(r, lo, hi)), ask = r(0, n - 1);
    const rest = e.reduce((s, v, k) => (k === ask ? s : s + v), 0), x = 360 - rest;
    if (x < xlo || x > xhi || x % 5) continue;
    e[ask] = x;
    const V = NM[ask], vs = [...names(n)].filter((c) => c !== V), vals = e.filter((v, k) => k !== ask);
    return {
      q: `${gon(n)} ${names(n)} で、頂点 ${vs.join("、")} の外角の大きさは、それぞれ ${vals.map((v) => `${v}°`).join("、")} である。頂点 ${V} の外角の大きさは？`,
      ans: x,
      unit: "度",
      hint: "多角形の外角の和は、何度だったかな？ 求めたい外角のほかの外角の和は、何度かな？",
      steps: [`多角形の外角の和は、何角形でも 360°。`, `頂点 ${V} の外角＝360°−(${vals.map((v) => `${v}°`).join("+")})＝${x}°`],
    };
  }
  return { skip: true };
}
/** ロボット：まっすぐ L m 進み、その場で左へ θ° 向きを変える、をくり返す */
const ROBOT = (L, th) => `ロボットが、「まっすぐ ${L} m 進み、その場で左へ ${th}° 向きを変える」ことをくり返す。はじめの位置にもどり、はじめと同じ向きになるまで続ける。`;

// ── n を使った式を選ぶ（06d07a・b）────────────────────────────────────
/** 正n角形の1つの内角（度）を表す式。ans＝正しい式。share＝正解と形がにている誤答、other＝形がちがう誤答。どれも、正解と同じ式にはならない */
const EXPR = {
  sum: {
    how: "内角の和を n でわる",
    ans: "\\frac{180(n-2)}{n}",
    share: ["\\frac{180n-2}{n}", "\\frac{180(n+2)}{n}", "\\frac{360(n-2)}{n}", "\\frac{180(n-2)}{2}"],
    other: ["180(n-2)", "\\frac{360}{n}", "180-\\frac{180}{n}", "\\frac{180}{n}"],
    steps: [`正${$("n")}角形の内角の和は ${$("180(n-2)")} 度。`, `内角は ${$("n")} 個とも等しいので、内角の和を ${$("n")} でわって　${$("\\frac{180(n-2)}{n}")} 度。`],
    hint: "正 $n$ 角形の内角の和は、どう表せたかな？ 正多角形の内角は、すべてどうなっているかな？",
  },
  ext: {
    how: "180° から、1つの外角をひく",
    ans: "180-\\frac{360}{n}",
    share: ["180-\\frac{180}{n}", "180-360n", "180-\\frac{360}{n-2}", "180-\\frac{720}{n}"],
    other: ["\\frac{360}{n}", "\\frac{180-360}{n}", "\\frac{360}{n}-180", "360-\\frac{180}{n}"],
    steps: [`正${$("n")}角形の外角の和は 360° で、外角は ${$("n")} 個とも等しいので、1つの外角は ${$("\\frac{360}{n}")} 度。`, `内角＝180°−外角 だから　${$("180-\\frac{360}{n}")} 度。`],
    hint: "正 $n$ 角形の 1つの外角は、どう表せたかな？ 同じ頂点で、内角と外角の和は何度だったかな？",
  },
};
function exprQ(r, key) {
  const E = EXPR[key], ans = $(E.ans);
  const nShare = pick(r, [1, 2]), wrongs = [...shuffle(r, E.share).slice(0, nShare), ...shuffle(r, E.other).slice(0, 3 - nShare)];
  return {
    q: `正 $n$ 角形の 1つの内角の大きさ（単位は度）を、「${E.how}」考え方で、$n$ を使った式に表す。正しい式は、次のうちどれか。`,
    ans,
    choices: choices4(r, ans, wrongs.map($)),
    hint: E.hint,
    steps: E.steps,
  };
}

