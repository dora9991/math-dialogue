/** 割合 c÷n が、ちょうど小数第2位までで割りきれるか */
const exact = (c, n) => Number.isInteger(round((100 * c) / n, 6));
/** 「c ÷ n ＝ 0.45」（割りきれなければ四捨五入して「≒」） */
const fr = (c, n) => `${c} ÷ ${n} ${exact(c, n) ? "＝" : "≒"} ${f2(roundHalf(c / n, 2))}`;

