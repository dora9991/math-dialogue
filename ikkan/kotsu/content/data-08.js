/** 回数 n のうち、起こった回数 c の相対度数を聞く */
const mkRel = (objs, ns, lo, hi, tight = false) => (r) => {
  const o = pick(r, objs), n = pick(r, ns), pr = tight && n >= 500 ? r(48, 52) : r(lo, hi), c = Math.round((n * pr) / 100) + r(-1, 1);
  const rel = relFreq(c, n, 2);
  if (rel == null || c < 1 || c >= n) return { skip: true };
  return {
    q: `${o.obj}を ${n}回投げて、${o.up}回数を調べたところ、${c}回であった。相対度数は？（小数第3位を四捨五入して、小数第2位まで）`,
    ans: rel,
    hint: "相対度数は、（起こった回数）÷（投げた回数）で求める。",
    steps: [`相対度数 ＝ ${o.up}回数 ÷ 投げた回数`, `${c} ÷ ${n} ${exact(c, n) ? "＝" : "≒"} ${f2(rel)}`],
  };
};

// ── 3人が同じ回数ずつ投げる（はじめからの合計） ──────────────────────
const NM = ["Aさん", "Bさん", "Cさん"];
function three(r) {
  const o = pick(r, OBJ), k = pick(r, [20, 25, 30, 40, 50]);
  const cs = [0, 1, 2].map(() => Math.max(1, Math.round((k * r(30, 70)) / 100)));
  const intro = `Aさん・Bさん・Cさんが、${o.obj}を ${k}回ずつ投げた。${o.up}回数は、Aさんが ${cs[0]}回、Bさんが ${cs[1]}回、Cさんが ${cs[2]}回であった。`;
  return { o, k, cs, intro };
}

// ── 回数がふえると落ち着いていく相対度数 ────────────────────────
/** 回数の列 ns に対する、起こった回数と相対度数。落ち着く値は p。最初の nDev 個は大きくゆれ、それ以降は p に（小数第2位まで）そろう */
function settle(r, ns, p, nDev) {
  const sg = r(0, 1) ? 1 : -1, devs = [r(6, 10) / 100, -r(3, 6) / 100, r(1, 3) / 100];
  const c = ns.map((n, i) => {
    if (i < nDev) return Math.round(n * (p + sg * devs[i]));
    const m = Math.floor(0.004 * n);
    return Math.round(n * p) + r(-m, m);
  });
  const rel = c.map((x, i) => relFreq(x, ns[i], 2));
  if (rel.some((x) => x == null)) return null;
  if (rel.slice(nDev).some((x) => Math.abs(x - p) > 1e-9)) return null;
  if (rel.slice(0, 2).some((x) => Math.abs(x - p) < 0.025)) return null;
  return { n: ns, c, rel };
}
const joinN = (a, s) => a.map((x) => `${x}${s}`).join("、");

// ── 多数回の実験で、ある回数までの相対度数が「ちょうど」わかっている問題の候補 ───────────
/** n1 回まで R1、n2 回まで R2（どちらもちょうどの値）。あとの (n2−n1) 回だけの相対度数 ＝ (n2×R2 − n1×R1) ÷ (n2−n1)。ちょうど小数第2位までで、2つの平均とは 0.01 以上ちがう */
const SEG = [];
for (const n1 of [100, 200, 400, 500]) for (const n2 of [200, 400, 500, 800, 1000]) {
  if (n2 <= n1) continue;
  for (let a = 30; a <= 70; a++) for (let b = 30; b <= 70; b++) {
    const c1 = (n1 * a) / 100, c2 = (n2 * b) / 100;
    if (!Number.isInteger(c1) || !Number.isInteger(c2) || c2 <= c1) continue;
    const x = ((c2 - c1) * 100) / (n2 - n1);
    if (!Number.isInteger(round(x, 6)) || x < 20 || x > 80 || Math.abs(x - (a + b) / 2) < 1) continue;
    SEG.push({ n1, n2, a, b, c1, c2, x });
  }
}

