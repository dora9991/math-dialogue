//   ikkan の演習プリント（shiki-08.dr.1〜8）・小テスト（shiki-08.qz.1〜4）を、コツコツくんのテンプレートにしたもの。
//   テンプレート id＝「08」＋ d（演習）／q（小テスト）＋ ikkan の問題の番号（＋ 小問・型ごとに a, b…）。例：08d03 ＝ shiki-08.dr.3
//   「説明しよう」の問題は、書けないので、説明の中の1つの段階（文字でおく・式を変形する・式を読む）を、
//   数で聞く（□ に入る数・余り・数の個数）か、4択（式を選ぶ）にして移した。
//   係数・余り・条件にあう数は、すべて計算（数の代入・全数調べ）で出す（手で書かない）。
//   4択の誤答は、ありがちなまちがいで、正解と式として同じにならないものだけ（式は、文字の係数の組で比べて除く）。
// ============================================================
import { t, pick, choices4, shuffle } from "../kit.js";
import { unitFor } from "../unit-kit.js";

