// ── 小さな道具 ────────────────────────────────────────────
const $ = (s) => `$${s}$`;
/** 4択（式の TeX）：正解 right と、まちがい wrongs（正解と同じ文字列は除く） */
const mk4 = (r, right, wrongs) => {
  const ws = shuffle(r, [...new Set(wrongs)].filter((w) => w !== right));
  if (ws.length < 3) throw new Error(`誤答が足りない: ${right}`);
  return choices4(r, $(right), ws.slice(0, 3).map($));
};
/** 符号つきの定数項："+3"、"-2"、""（0 のとき） */
const sg = (c) => (c > 0 ? `+${c}` : c < 0 ? `-${-c}` : "");
const PAIR2 = [["x", "y"], ["a", "b"], ["s", "t"], ["m", "n"], ["p", "q"]];   // 位の数を表す文字の組
const PAIR_MN = [["m", "n"], ["a", "b"], ["p", "q"]];
/** mult×(au·u + av·v + e) + one の式。tex と、式として同じかどうかを見る key */
const form = (u, v, mult, au, av, e, one = 0) => {
  const inner = `${au < 0 ? "-" : ""}${u}${av > 0 ? "+" : "-"}${v}${sg(e)}`;
  return { tex: (mult === 1 ? inner : `${mult}(${inner})`) + sg(one), key: [mult * au, mult * av, mult * e + one].join() };
};
/** 4択（形のそろった式）：right、wrongs は { tex, key }。key が正解と同じものは入れない */
const mkForm4 = (r, right, wrongs) => {
  const seen = new Set([right.key]), texs = new Set([right.tex]), ws = [];
  for (const w of shuffle(r, wrongs)) { if (seen.has(w.key) || texs.has(w.tex)) continue; seen.add(w.key); texs.add(w.tex); ws.push(w); }
  if (ws.length < 3) throw new Error(`誤答が足りない: ${right.tex}`);
  return choices4(r, $(right.tex), ws.slice(0, 3).map((w) => $(w.tex)));
};
/** f(a, b) / g(a, b) が、a、b によらず一定の数かを確かめて、その数を返す（一定でなければ例外） */
const constRatio = (f, g, pts) => {
  let val = null;
  for (const [a, b] of pts) {
    const x = f(a, b), y = g(a, b);
    if (y === 0) continue;
    const q = x / y;
    if (val === null) val = q; else if (Math.abs(val - q) > 1e-9) throw new Error("一定の数にならない");
  }
  return val;
};
const PTS = [[7, 2], [5, 3], [9, 4], [8, 1], [6, 5], [3, 8]];

// ── n を使って表す・位の数で表す（08d01a〜d、08q01a〜c） ───────────────
/** 偶数・奇数（文字は letters のどれか） */
const evenOddQ = (r, which, letters = ["n", "m", "k"]) => {
  const v = pick(r, letters), odd = which ? which === "odd" : r(0, 1) === 1;
  const right = odd ? `2${v}+1` : `2${v}`;
  return {
    q: `$${v}$ を整数とする。${odd ? "奇数" : "偶数"}を、$${v}$ を使って表すと、どれか。`,
    ans: $(right),
    choices: mk4(r, right, odd ? [`2${v}`, `${v}+1`, `2${v}+2`, `3${v}+1`, `${v}^{2}`] : [`2${v}+1`, `${v}+2`, `3${v}`, `${v}^{2}`, `${v}+1`]),   // 2n−1、2n+3、4n などは、奇数・偶数になるので、誤答に入れない
    hint: odd ? "奇数は、偶数と どれだけちがう数かな。偶数は 2 に何をかけた数かな。" : "偶数は、2 でわり切れる整数。2 に何をかけた数と考えられるかな。",
    steps: odd ? [`偶数は 2 に整数をかけた数だから、$2${v}$ と表される。`, `奇数は、偶数より 1 大きい（または 1 小さい）数。$2${v}+1$ と表される。`] : ["偶数は 2 の倍数、つまり 2 に整数をかけた数。", `整数を $${v}$ とすると、$2${v}$ と表される。`],
  };
};
/** k の倍数 */
const multipleQ = (r) => {
  const k = r(3, 9), v = pick(r, ["n", "m", "a"]), right = `${k}${v}`;
  return {
    q: `$${v}$ を整数とする。${k}の倍数を、$${v}$ を使って表すと、どれか。`,
    ans: $(right),
    choices: mk4(r, right, [`${v}+${k}`, `${k}${v}+1`, `${v}-${k}`, `\\frac{${v}}{${k}}`]),   // k(n+1) などは、やはり k の倍数になるので、誤答に入れない
    hint: `${k}の倍数は、${k} にどんな数をかけた数かな。`,
    steps: [`${k}の倍数は、${k} に整数をかけた数。`, `整数を $${v}$ とすると、$${right}$ と表される。`],
  };
};
/** 十の位の数が x、一の位の数が y の2けたの自然数（swap なら、位を入れかえた数） */
const digitQ = (r, swap) => {
  const [x, y] = pick(r, PAIR2);
  const right = swap ? `10${y}+${x}` : `10${x}+${y}`;
  const wrongs = swap ? [`10${x}+${y}`, `${x}${y}`, `${x}+${y}`, `10(${x}+${y})`, `10${x}${y}`] : [`10${y}+${x}`, `${x}${y}`, `${x}+${y}`, `10(${x}+${y})`, `10${x}${y}`];
  return {
    q: swap
      ? `十の位の数が $${x}$、一の位の数が $${y}$ の2けたの自然数がある。この数の、十の位の数と一の位の数を入れかえた数を、式で表すと、どれか。`
      : `十の位の数が $${x}$、一の位の数が $${y}$ の2けたの自然数を、式で表すと、どれか。`,
    ans: $(right),
    choices: mk4(r, right, wrongs),
    hint: swap ? "入れかえると、十の位の数になるのは、もとの十の位と一の位のどちらかな。47 で考えてみよう。" : "47 は、十の位の 4 と一の位の 7 を使って、どう表せるかな。",
    steps: swap
      ? [`入れかえた数は、十の位の数が $${y}$、一の位の数が $${x}$。`, `十の位の数 $${y}$ は、10 が $${y}$ 個ぶんだから $10${y}$。一の位の数は $${x}$。`, `$${right}$ と表される。`]
      : [`十の位の数 $${x}$ は、10 が $${x}$ 個ぶんだから $10${x}$。一の位の数は $${y}$。`, `$${right}$ と表される。`],
  };
};

