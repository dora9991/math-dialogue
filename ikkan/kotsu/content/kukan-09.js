import { t, pick, choices4, shuffle } from "../kit.js";
import { unit } from "../kukan-kit.js";

const SQ = "cm²";
const pi = (k) => (k === 1 ? "π" : `${k}π`);   // 係数が 1 のときは、「1π」と書かない

// ───────── 長方形・三角形・台形の底面の角柱 ─────────
/** 底面が縦 a・横 b の長方形で、高さ h の四角柱 */
const rectPrism = (A, B, H, hint) => (r) => {
  const a = r(...A), b = r(...B), h = r(...H);
  if (a === b) return { skip: true };
  const side = (a + b) * 2 * h, base = a * b, ans = side + base * 2;
  return {
    q: `底面が縦 ${a}cm、横 ${b}cm の長方形で、高さが ${h}cm の四角柱の表面積は何 cm² か。`,
    ans,
    unit: SQ,
    hint,
    steps: [
      `側面積 … 底面のまわりの長さ×高さ = (${a}+${b})×2×${h} = ${side}`,
      `底面積 … ${a}×${b} = ${base}`,
      `表面積 = 側面積 + 底面積×2 = ${side} + ${base}×2 = ${ans}（cm²）`,
    ],
  };
};
const HINT_PRISM = "展開図を思いうかべよう。側面積は「底面のまわりの長さ×高さ」。底面は 2つある。";

/** 底面が直角三角形（3辺 p, q, c。c が斜辺）で、高さ h の三角柱 */
const TRI = [[3, 4, 5], [6, 8, 10], [5, 12, 13], [9, 12, 15], [8, 15, 17]];
const triPrism = (tris, H) => (r) => {
  const [p, q, c] = pick(r, tris), h = r(...H);
  const side = (p + q + c) * h, area = (p * q) / 2, ans = side + area * 2;
  return {
    q: `底面が 3辺 ${p}cm、${q}cm、${c}cm の直角三角形で、高さが ${h}cm の三角柱の表面積は何 cm² か。`,
    ans,
    unit: SQ,
    hint: HINT_PRISM + "直角をはさむ 2辺が、三角形の底辺と高さ。",
    steps: [
      `側面積 … (${p}+${q}+${c})×${h} = ${side}`,
      `底面積 … ${p}×${q}÷2 = ${area}`,
      `表面積 = ${side} + ${area}×2 = ${ans}（cm²）`,
    ],
  };
};

/** 底面が台形（上底 u・下底 l。上底・下底に垂直な辺が b、もう1つの辺が c）で、高さ H の四角柱 */
const TRAP = [[3, 4, 5], [4, 3, 5], [6, 8, 10], [8, 6, 10], [5, 12, 13], [12, 5, 13], [9, 12, 15], [12, 9, 15]];   // [下底−上底, 台形の高さ b, ななめの辺 c]
const trapPrism = (r) => {
  const [dx, b, c] = pick(r, TRAP), u = r(2, 6), l = u + dx, H = r(3, 9);
  if (((u + l) * b) % 2) return { skip: true };
  const P = u + l + b + c, side = P * H, area = ((u + l) * b) / 2, ans = side + area * 2;
  return {
    q: `底面が台形（上底 ${u}cm、下底 ${l}cm で、上底・下底に垂直な辺が ${b}cm、もう1つの辺が ${c}cm）で、柱の高さが ${H}cm の四角柱の表面積は何 cm² か。`,
    ans,
    unit: SQ,
    hint: HINT_PRISM + "台形の 4つの辺を、ぜんぶ たそう。",
    steps: [
      `側面積 … 底面のまわりの長さ×高さ = (${u}+${l}+${b}+${c})×${H} = ${side}`,
      `底面積 … (${u}+${l})×${b}÷2 = ${area}`,
      `表面積 = ${side} + ${area}×2 = ${ans}（cm²）`,
    ],
  };
};

// ───────── 円柱 ─────────
const HINT_CYL = "展開図の側面は長方形。横は底面の円周、縦は高さ。底面の円は 2つある。";
const cylSteps = (rad, h) => [
  `側面積 … 横は底面の円周 2π×${rad}、縦は高さ ${h} の長方形 → 2π×${rad}×${h} = ${2 * rad * h}π`,
  `底面積 … π×${rad}² = ${rad * rad}π`,
  `表面積 = 側面積 + 底面積×2 = ${2 * rad * h}π + ${rad * rad}π×2 = ${2 * rad * h + 2 * rad * rad}π（cm²）`,
];
const cylinder = (R, H) => (r) => {
  const rad = r(...R), h = r(...H);
  return { q: `底面の半径が ${rad}cm、高さが ${h}cm の円柱の表面積は □π cm²。□は？`, ans: 2 * rad * h + 2 * rad * rad, hint: HINT_CYL, steps: cylSteps(rad, h) };
};

// ───────── a + bπ の形になる問い ─────────
const ASK = (w) => (w === "a" ? "整数の部分 $a$ は？" : "$\\pi$ の係数 $b$ は？");
const FORM = "表面積を $a+b\\pi$ cm²（$a$、$b$ は整数）と表すとき、";

/** おうぎ形の底面：(R, θ) のうち、まわりの弧の長さも底面積も「整数 × π」になる組 */
const SECTORS = [];
for (const th of [60, 90, 120, 180]) for (let R = 2; R <= 12; R++) {
  if ((R * th) % 180 === 0 && (R * R * th) % 360 === 0) SECTORS.push([R, th]);
}

