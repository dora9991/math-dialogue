//   円が入るときは、中1空間図形（c6_kukan.js）と同じ「表面積は □π cm²。□は？」。
//   円錐の解説（steps）は、ikkan と同じ流れ：弧の長さ＝底面の円周 → 母線を半径とする円の周 → 弧は円周の何分のいくつか → 側面積。
