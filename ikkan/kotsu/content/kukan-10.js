import { t, pick, choices4, shuffle, fracTex } from "../kit.js";
import { unit } from "../kukan-kit.js";

const SQ = "cm²";

// ───────── 正四角錐 ─────────
/** 底面が 1辺 a の正方形で、側面の三角形の高さが s の正四角錐（s は、a の半分の 1.3倍以上。針のように細長い角錐や、ぺしゃんこの角錐を、さける） */
const sqPyramid = (A, S) => (r) => {
  const a = r(...A), s = r(Math.max(S[0], Math.ceil((1.3 * a) / 2)), S[1]);
  const side = 2 * a * s, base = a * a;
  return {
    q: `底面が 1辺 ${a}cm の正方形で、側面の三角形の高さが ${s}cm の正四角錐の表面積は何 cm² か。`,
    ans: side + base,
    unit: SQ,
    hint: "展開図を思いうかべよう。側面は、合同な二等辺三角形が 4つ。錐体の底面は 1つだけ。",
    steps: [
      `側面の三角形は、底辺 ${a}cm・高さ ${s}cm のものが 4つ。側面積 … $\\frac{1}{2}$×${a}×${s}×4 = ${side}`,
      `底面積 … ${a}×${a} = ${base}`,
      `表面積 = 側面積 + 底面積 = ${side} + ${base} = ${side + base}（cm²）`,
    ],
  };
};

// ───────── 円錐 ─────────
const HINT_CONE = "側面はおうぎ形で、弧の長さは底面の円周に等しい。側面積は、「母線を半径とする円の面積」×「弧が、その円周の何分のいくつか」。";
/** 底面の半径 rad・母線 l の円錐の側面積を、弧→円周→割合→面積 の順に求める説明（3行） */
const coneSide = (rad, l) => [
  `側面のおうぎ形の弧の長さ = 底面の円周 = 2π×${rad} = ${2 * rad}π`,
  `母線 ${l}cm を半径とする円の周 = 2π×${l} = ${2 * l}π。弧は、その円周の $\\frac{${2 * rad}\\pi}{${2 * l}\\pi}$ = $${fracTex(rad, l)}$`,
  `側面積 … π×${l}²×$${fracTex(rad, l)}$ = ${rad * l}π`,
];
/** 底面の半径 R・母線 L の円錐の表面積（□π の □）を求める問い */
const cone = (R, LMIN, LMAX) => (r) => {
  const rad = r(...R), l = r(Math.max(rad + 2, LMIN), LMAX);
  return {
    q: `底面の半径が ${rad}cm、母線の長さが ${l}cm の円錐の表面積は □π cm²。□は？`,
    ans: rad * l + rad * rad,
    hint: HINT_CONE,
    steps: [...coneSide(rad, l), `底面積 … π×${rad}² = ${rad * rad}π　　表面積 = ${rad * l}π + ${rad * rad}π = ${rad * l + rad * rad}π（cm²）`],
  };
};

/** 「側面が、半径 l のおうぎ形（中心角 θ）の円錐」：θ・l の組（底面の半径 = lθ/360 が 2以上の整数） */
const sectors = (ths, lmax) => {
  const out = [];
  for (const th of ths) for (let l = 4; l <= lmax; l++) { const rad = (l * th) / 360; if (Number.isInteger(rad) && rad >= 2 && rad < l) out.push([l, th, rad]); }
  return out;
};
const SEC1 = sectors([60, 90, 120, 150, 180, 240, 270], 18);
const SEC2 = sectors([150, 210, 240, 270, 300], 24);
