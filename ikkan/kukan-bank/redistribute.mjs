const map = {}, detail = [];
for (const [a, b, no, what, note] of RULES) {
  for (let i = a; i <= b; i++) {
    const id = `J1-SP-${String(i).padStart(3, "0")}`;
    if (map[id]) throw new Error(`${id} が2回出てくる`);
    map[id] = `kukan-${String(no).padStart(2, "0")}`;
  }
  detail.push({ ids: `J1-SP-${String(a).padStart(3, "0")}〜${String(b).padStart(3, "0")}`, count: b - a + 1, lesson: `kukan-${String(no).padStart(2, "0")}`, lessonName: LESSON[no], what, note });
}
for (let i = 1; i <= 150; i++) if (!map[`J1-SP-${String(i).padStart(3, "0")}`]) throw new Error(`J1-SP-${i} が振り分けられていない`);

const perLesson = {};
Object.values(map).forEach((l) => { perLesson[l] = (perLesson[l] || 0) + 1; });
fs.writeFileSync(path.join(HERE, "existing-redistribution.json"), JSON.stringify({ perLesson, rules: detail, map }, null, 1) + "\n");
