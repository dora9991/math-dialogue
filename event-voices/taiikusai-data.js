// 体育大会「感想ひろば」のデータ。
// window.EVENT_DATA は感想文字列の配列。1件＝1人分。
// 順番はランダムに人へ割り当てられる（誰が何番目でも個人が特定できないよう、名前・出席番号は持たない）。
//
// ▼実データへの差し替え方
//   1) make-data.mjs を使う場合：感想を1行1件で書いた raw-comments.txt を用意し、
//      `node make-data.mjs raw-comments.txt` を実行すると、このファイルが自動生成される。
//   2) 手で書き換える場合：下の配列の中身をそのまま実データの文字列に置き換えるだけでよい。
//      （件数は105件でなくてもよい。配列の長さに応じて人数が自動で変わる。）
//
// 以下はレイアウト確認用のダミー文です。公開前に必ず実データに差し替えてください。
window.EVENT_DATA = Array.from({ length: 105 }, (_, i) =>
  `サンプル感想 ${String(i + 1).padStart(3, "0")}：ここに実際の体育大会の感想文が入ります。`
);
