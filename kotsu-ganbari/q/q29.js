// 問29：おうぎ形の弧の長さと面積
import { seg, arc, ang, path, txt, polar } from "../dsl.js";

const f = (v) => Math.round(v * 10) / 10;
const C = [230, 180], R = 150;                       // 円全体の中心と半径（図の大きさ。4cm や 9cm の目もりではない）
const pt = (deg) => polar(C, R, deg).map(f);

// 点線の「寸法の弧」（a→b、bulge＝ふくらみ。進む向きの左が＋）
function dim(id, a, b, bulge, label) {
  const dx = b[0] - a[0], dy = b[1] - a[1], L = Math.hypot(dx, dy), n = [dy / L, -dx / L];
  const m = [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2];
  const c = [m[0] + n[0] * bulge * 2, m[1] + n[1] * bulge * 2], pk = [m[0] + n[0] * bulge, m[1] + n[1] * bulge];
  return [
    path(`M${f(a[0])} ${f(a[1])}Q${f(c[0])} ${f(c[1])} ${f(b[0])} ${f(b[1])}`, { id, dash: true, c: "g" }),
    txt(pk[0], pk[1] + 5, label, { id: id + "t", size: 16, c: "g" }),
  ];
}
const sector = (from, to) => `M${C[0]} ${C[1]}L${pt(from)[0]} ${pt(from)[1]}A${R} ${R} 0 0 0 ${pt(to)[0]} ${pt(to)[1]}Z`;

// (1) 半径4cm・中心角45°：0°〜45°
