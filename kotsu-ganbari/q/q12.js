import { P, seg, arc, rt, geo, dirDeg } from "../dsl.js";

// 印刷物の△ABC（写真から読みとった形。BCは水平。∠A, ∠B, ∠C はすべて鋭角なので、垂線の足Hは辺ABの上にくる）
const s = 1.1;
const m = (x, y) => [(x - 1253) * s + 60, (y - 1663) * s + 60];
const A = m(1433, 1663), B = m(1253, 1852), C = m(1483, 1853);

// 点Cから直線ABへの垂線の作図
const H = geo.foot(C, A, B);                                    // 答え：垂線の足
const r1 = geo.dist(C, H) * 1.08;                               // ① Cを中心にした円の半径（CからABまでの距離より大きく）
const [D, E] = geo.interLC(A, B, C, r1);                        // 円と直線ABの交点（Bに近いほうが D…の順に返る）
const r2 = (geo.dist(D, E) / 2) * 1.5;                          // ②③ D, E を中心にした同じ半径（DEの半分より大きく）
const [g1, g2] = geo.interCC(D, r2, E, r2);
const side = (p) => (A[0] - B[0]) * (p[1] - B[1]) - (A[1] - B[1]) * (p[0] - B[0]);
const F = side(g1) * side(C) < 0 ? g1 : g2;                     // ABをはさんで、Cの反対がわの交点

const near = (c, r, p, w, o = {}) => arc(c, r, dirDeg(c, p) - w, dirDeg(c, p) + w, o);   // 交点のまわりだけの短い弧

