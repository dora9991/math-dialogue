const r = 6, arcLen = 2 * Math.PI;
const frac = arcLen / (2 * Math.PI * r);          // 1/6
const theta = 360 * frac;                         // 60
const area = Math.PI * r * r * frac;              // 6π
if (Math.abs(theta - 60) > 1e-9 || Math.abs(area - 6 * Math.PI) > 1e-9) throw new Error("計算が合いません");

