// 印刷物の図：中心は右上の頂点。ここから、左下ななめ（210°）と真下（270°）に半径がのびる。
const R = 120;                                   // 図の半径（6cm にあたる）
const O = [250, 152];
const A = polar(O, R, 210), B = polar(O, R, 270); // 半径の先（弧の両はし）
const C0 = geo.circumcenter(A, O, B);              // 印刷物の点線の弧（3点 O, A, B を通る）の中心
