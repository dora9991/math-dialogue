/** たちの かたちの なかま（はこ・さいころ・つつ・ボール） */
const SOLID = {
  はこ: ["ティッシュの はこ", "じしょ", "けしゴム"],
  さいころ: ["さいころ"],
  つつ: ["ジュースの かん", "かんづめ", "スティックのり"],
  ボール: ["ビーだま", "ピンポンだま", "サッカーボール"],
};
const SOLID_ALL = Object.entries(SOLID).flatMap(([k, xs]) => xs.map((x) => [x, k]));
/** ふん・ぷん */
const fun = (m) => ([2, 5, 7, 9].includes(m % 10) ? "ふん" : "ぷん");
/** 3じ / 3じ25ふん */
const jifun = (h, m) => (m === 0 ? `${h}じ` : `${h}じ${m}${fun(m)}`);
/** くりあがりの たしざんの とき方（大きい ほうで 10 を つくる） */
const kuriSteps = (a, b) => {
  const [big, small] = a >= b ? [a, b] : [b, a];
  const s = a + b;
  return [`${small} を ${10 - big} と ${s - 10} に わける`, `${big} と ${10 - big} で 10`, `10 と ${s - 10} で ${s}`];
};
/** とけいの つぎの すうじ（12 の つぎは 1） */
const nextH = (h) => (h % 12) + 1;
const prevH = (h) => ((h + 10) % 12) + 1;

