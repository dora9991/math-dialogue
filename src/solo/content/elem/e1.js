// ── 小さな道具 ─────────────────────────────────────────
/** 数の4択（min より小さい数は出さない） */
const nc = (r, ans, traps = [], min = 0) => {
  const ds = [1, -1, 2, -2, 3, -3, 4, 5, -4, 10];
  const off = r(0, ds.length - 1);
  return choices4(r, ans, traps.filter((x) => Number.isInteger(x) && x >= min), (i) => {
    const v = ans + ds[(i + off) % ds.length];
    return v >= min ? v : null;
  });
};
/** a〜b の整数の配列 */
const range = (a, b) => Array.from({ length: Math.max(0, b - a + 1) }, (_, i) => a + i);
/** ひとり・ふたり・3にん */
const nin = (n) => (n === 1 ? "ひとり" : n === 2 ? "ふたり" : `${n}にん`);
/** 1ぽん・2ほん・3ぼん */
const hon = (n) => {
  const d = n % 10;
  return `${n}${[1, 6, 8, 0].includes(d) ? "ぽん" : d === 3 ? "ぼん" : "ほん"}`;
};
/** かず＋かぞえかた（にん だけ とくべつ） */
const cnt = (n, c) => (c === "にん" ? nin(n) : `${n}${c}`);
/** ふん・ぷん */
const fun = (m) => ([2, 5, 7, 9].includes(m % 10) ? "ふん" : "ぷん");
/** 3じ / 3じ25ふん */
const jifun = (h, m) => (m === 0 ? `${h}じ` : `${h}じ${m}${fun(m)}`);
/** くりあがりの たしざんの とき方（大きい ほうで 10 を つくる） */
const kuriSteps = (a, b) => {
  const [big, small] = a >= b ? [a, b] : [b, a];
  const s = a + b;
  return [`${small} を ${10 - big} と ${s - 10} に わける`, `${big} と ${10 - big} で 10`, `10 と ${s - 10} で ${s}`];
};
/** とけいの つぎの すうじ（12 の つぎは 1） */
const nextH = (h) => (h % 12) + 1;
const prevH = (h) => ((h + 10) % 12) + 1;

