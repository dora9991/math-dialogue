function kan4(n) {
  const units = ["千", "百", "十", ""];
  const ds = [dig(n, 3), dig(n, 2), dig(n, 1), dig(n, 0)];
  return ds.map((d, i) => (d === 0 ? "" : (d === 1 && i < 3 ? "" : KD[d]) + units[i])).join("");
}
