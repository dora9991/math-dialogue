/** 数の4択（min より小さい数は出さない） */
const nc = (r, ans, traps = [], min = 0) => {
  const ds = [1, -1, 2, -2, 10, -10, 3, 5, -5, 100];
  const off = r(0, ds.length - 1);
  return choices4(r, ans, traps.filter((x) => Number.isFinite(x) && x >= min), (i) => {
    const v = ans + ds[(i + off) % ds.length];
    return v >= min ? v : null;
  });
};
