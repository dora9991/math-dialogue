    const hl = (y) => items.push({ k: 'seg', a: [0, y], b: [W, y], c: LINE, wd: 2 });
    hl(H); hl(0);
    items.push({ k: 'seg', a: [0, 0], b: [0, H], c: LINE, wd: 2 }, { k: 'seg', a: [W, 0], b: [W, H], c: LINE, wd: 2 }, { k: 'seg', a: [w0, 0], b: [w0, H], c: LINE, wd: 2 });
