    if (inc && cup) F = x => cy - hh + 2 * hh * s((x - x0) / (2 * hw));
    else if (inc) F = x => cy + hh - 2 * hh * s((x1 - x) / (2 * hw));
    else if (cup) F = x => cy - hh + 2 * hh * s((x1 - x) / (2 * hw));
